    /// Что воин говорит через строй — и кому именно.
    ///
    /// До сих пор собеседник на реплику не влиял вовсе:
    /// <c>DialogueTrigger.GetDialogueLine</c> принимал его и не смотрел,
    /// а <c>DialogueLoader</c> выбирал строку по греху и морали говорящего.
    /// Двадцать одна фраза на всю игру, и гордый говорил жадному то же,
    /// что унылому.
    ///
    /// Здесь фраза собирается по встрече. Слоёв несколько, и выигрывает
    /// самый частный: чем больше игра знает об этих двоих, тем точнее
    /// они говорят.
    ///
    /// <list type="number">
    /// <item><b>Брат по оружию</b> — если рядом тот, с кем пришёл;</item>
    /// <item><b>Грех против греха</b> — сорок девять сочетаний, по три
    ///       фразы на каждое;</item>
    /// <item><b>По умолчанию</b> — семь грехов, по три фразы.</item>
    /// </list>
    ///
    /// <b>Из трёх выбирается не жребием.</b> Правило проекта «одинаковый
    /// вход даёт одинаковый выход» касается и слов: та же пара в той же
    /// ситуации обязана сказать то же самое, иначе игрок не сможет
    /// узнавать своих по речи. Номер считается устойчивым хешем от имён
    /// и ситуации — разный у разных пар, один и тот же у одной.
    ///
    /// Три фразы, а не одна, потому что одна на сорок девять сочетаний
    /// звучит как реплика, а три — как характер.
    /// </summary>
    public static class EncounterLines
    {
        /// <summary>Порядок как в <see cref="SinType"/>: Жадность, Гордыня,
        /// Гнев, Зависть, Похоть, Чревоугодие, Уныние.</summary>
        private const int Sins = 7;

        // ---------- выбор ----------

        /// <summary>
        /// Реплика говорящего о собеседнике. Пусто — значит сказать нечего,
        /// и вызывающий обязан это пережить, а не показать пустой пузырь.
        /// </summary>
        public static string Say(Warrior speaker, Warrior target, string situation)
        {
            if (speaker?.Soul == null) return string.Empty;

            var lines = Pick(speaker, target);
            if (lines == null || lines.Length == 0) return string.Empty;

            return lines[Which(speaker, target, situation, lines.Length)];
        }

        private static string[] Pick(Warrior speaker, Warrior target)
        {
            int me = (int)speaker.Soul.Sin;

            // Брат перед собой — и всё остальное отходит. Это единственная
            // связь, которую движок читает в бою напрямую
            // (CombatDecisionContext.BrotherNearby), и слова обязаны
            // совпадать с тем, что он считает.
            if (Brother(speaker) && Brother(target)) return Brothers[me];

            if (target?.Soul == null) return Alone[me];

            return Against[me][(int)target.Soul.Sin];
        }

        private static bool Brother(Warrior w)
        {
            return w?.Soul?.Memory?.NarrativePerks != null
                && w.Soul.Memory.NarrativePerks.Exists(p => p.PerkName == "Брат по оружию");
        }

        /// <summary>
        /// Какая из трёх. Устойчивый хеш, а не жребий и не счётчик:
        /// счётчик дал бы разное при одинаковом входе после перезапуска,
        /// а <c>string.GetHashCode</c> в .NET не обещан одинаковым между
        /// запусками вовсе.
        /// </summary>
        private static int Which(Warrior speaker, Warrior target, string situation, int count)
        {
            uint h = 2166136261u;
            h = Fold(h, speaker.DisplayName);
            h = Fold(h, target != null ? target.DisplayName : "никто");
            h = Fold(h, situation);

            return (int)(h % (uint)count);
        }

        private static uint Fold(uint h, string s)
        {
            if (string.IsNullOrEmpty(s)) return h;

            for (int i = 0; i < s.Length; i++)
            {
                h ^= s[i];
                h *= 16777619u;
            }
            return h;
        }

