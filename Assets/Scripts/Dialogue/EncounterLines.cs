    /// Что воин говорит через строй — и кому именно.
    ///
    /// До сих пор собеседник на реплику не влиял вовсе:
    /// <c>DialogueTrigger.GetDialogueLine</c> принимал его и не смотрел,
    /// а <c>DialogueLoader</c> выбирал строку по греху и морали говорящего.
    /// Двадцать одна фраза на всю игру, и гордый говорил жадному то же,
    /// что унылому.
    ///
    /// Здесь фраза собирается по встрече. Слоёв несколько, и выигрывает
    /// самый частный: чем больше игра знает об этих двоих, тем точнее
    /// они говорят.
    ///
    /// <list type="number">
    /// <item><b>Брат по оружию</b> — если рядом тот, с кем пришёл;</item>
    /// <item><b>Легенда</b> — если собеседника узнали;</item>
    /// <item><b>Ремесло</b> — если у собеседника оно есть;</item>
    /// <item><b>Грех против греха</b> — сорок девять сочетаний;</item>
    /// <item><b>По умолчанию</b> — семь грехов.</item>
    /// </list>
    ///
    /// <b>Три фразы в клетке — это три морали.</b> Не три случайных
    /// варианта: жребия в проекте нет вовсе, а мораль у души неизменна,
    /// и потому предрешена. Злой, нейтральный и благочестивый одного
    /// и того же греха говорят разное — жадный злой глумится, жадный
    /// благочестивый стыдится своей жадности вслух.
    ///
    /// Так мораль слышна в каждом из шестидесяти трёх сочетаний, а не
    /// в одном общем тоне поверх всего. Порядок как в
    /// <see cref="MoralType"/>: злой, нейтральный, благочестивый.
    /// </summary>
    public static class EncounterLines
