namespace Sinbinder.AOS
{
    /// <summary>Насколько громко объявлять поступок.</summary>
    public enum Notice
    {
        /// <summary>Рядовое. Молчим.</summary>
        None = 0,

        /// <summary>Слово в журнале и значок над головой.</summary>
        Word = 1,

        /// <summary>Ещё и камера: игрок обязан это увидеть.</summary>
        Scene = 2,
    }

    /// <summary>
    /// Стоит ли объявлять то, что воин решил сам.
    ///
    /// Дыра, ради которой это заведено: движок производит уникальные
    /// моменты, а игрок их не видит. Отказ от <b>приказа</b> объявлен
    /// давно — журнал, тишина, отъезд камеры. Но приказ есть далеко
    /// не всегда, и поступок без приказа до сих пор не объявлялся ничем:
    /// воин разворачивался и убегал молча, а игрок замечал это краем
    /// глаза, если вообще смотрел в ту сторону.
    ///
    /// Это и есть предмет игры. Своеволие без приказа — не помеха
    /// управлению, а единственное, ради чего здесь семь шкал и
    /// тринадцать модулей.
    ///
    /// <b>Чего здесь нарочно нет — своего словаря.</b> Слова берутся
    /// у <see cref="PhraseGenerator.Doing"/>: два списка слов для одних
    /// и тех же действий разъезжаются молча, и об этом там написано
    /// прямым текстом.
    ///
    /// <b>Почему не всё подряд.</b> Решение принимается каждый тик,
    /// и объявлять каждое — значит не объявлять ничего. Отбор идёт
    /// в три сита: приказа не было; действие не рядовое; действие
    /// сменилось. Камеру тратит только <see cref="Notice.Scene"/>,
    /// и только на первый такой случай за бой — как тишина на первом
    /// отказе, которая от повторения перестаёт быть событием.
    ///
    /// Чистый класс, без Unity. Долю объявленных меряет стенд.
    /// </summary>
    public static class Moment
    {
        /// <summary>
        /// Поступок сделан сам, без приказа.
        ///
        /// Отказ от приказа сюда не попадает намеренно: у него своё
        /// событие, громче этого, и объявлять его дважды разными
        /// голосами значило бы спорить с самим собой.
        /// </summary>
        public static bool SelfWilled(DecisionContext context)
        {
            return context != null && !context.HasCommand;
        }

        /// <summary>
        /// Насколько громко объявить. <see cref="Notice.None"/> —
        /// не объявлять вовсе.
        /// </summary>
        public static Notice Worth(Decision decision, DecisionContext context)
        {
            if (!SelfWilled(context)) return Notice.None;

            // Колебание кончается бездействием: объявлять нечего,
            // воин ничего и не сделал.
            if (decision.Hesitated) return Notice.None;

            return Loudness(decision.Action);
        }

        /// <summary>
        /// Громкость самого действия.
        ///
        /// Отвесно разделены две вещи: что воин делает обычно —
        /// и что он делает, когда личность пересиливает.
        ///
        /// Открыто наружу ради пересказа вылазки: там есть действие,
        /// но нет ни решения, ни положения — бой уже кончился. Второй
        /// список «что стоит упоминать» разошёлся бы с этим на первой
        /// правке, а расходиться ему нельзя: в игре и в пересказе
        /// заметным обязано быть одно и то же.
        /// </summary>
        public static Notice Loudness(ActionType action)
        {
            switch (action)
            {
                // Камера. Два полюса, по которым игрок и узнаёт,
                // кого он поднял: бросил своих — или бросился за своими.
                // Плюс переход на другую сторону: реже и дороже обоих.
                case ActionType.Flee:
                case ActionType.SaveAlly:
                case ActionType.AcceptBribe:

                // Добыча сюда же, по решению автора: «если сам свернул —
                // хорошо». И правда — воин, бросивший драку ради блеска,
                // говорит о себе не меньше, чем беглец. Красть взгляд
                // под это не страшно: затвор всё равно тратится на первый
                // случай каждого рода за бой.
                case ActionType.Loot:
                    return Notice.Scene;

                // Слово. Случается часто и объясняет характер, но красть
                // под это взгляд — значит отнимать бой у игрока.
                case ActionType.BribeEnemy:
                case ActionType.Devour:
                case ActionType.Berserk:
                case ActionType.LastStand:
                case ActionType.DuelChallenge:
                case ActionType.Sacrifice:
                case ActionType.StealWeapon:
                case ActionType.Charm:
                case ActionType.EternalSleep:
                    return Notice.Word;

                // Рядовое: драка, стояние и послушание. Объявлять их —
                // всё равно что объявлять дыхание.
                default:
                    return Notice.None;
            }
        }
    }
}
