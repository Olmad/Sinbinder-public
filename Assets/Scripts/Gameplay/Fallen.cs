using System.Collections.Generic;

namespace Sinbinder.Gameplay
{
    /// <summary>
    /// Кого потеряли до того, как игрок проснулся.
    ///
    /// Пять палаток в лагере пустуют, и у каждой торчит колышек с именем.
    /// Ни строчки объяснения к ним не полагается: пустая палатка с именем —
    /// это вся предыстория, которая нужна (docs/09-PROLOGUE.md §4, сцена 1).
    /// Отряд нёс потери до начала демо, и игрок узнаёт об этом, ни разу
    /// не прочитав слова «потери».
    ///
    /// Кир Бессонный закреплён каноном и стоит первым. Остальные четверо
    /// каноном не закреплены — важно только, что их пятеро и что имена
    /// разные: одинаковые прочитались бы как ошибка сборки, а не как люди.
    ///
    /// Правило намеренно без Unity — проверяется стендом.
    /// </summary>
    public static class Fallen
    {
        private static readonly string[] _names =
        {
            "Кир Бессонный",
            "Тучан Хромой",
            "Веля Косторез",
            "Овсей Пустая Ладонь",
            "Гуда Меньшой",
        };

        /// <summary>Имена павших, в неизменном порядке.</summary>
        public static IReadOnlyList<string> Names => _names;

        /// <summary>Сколько их. Столько же должно быть пустых палаток.</summary>
        public static int Count => _names.Length;

        /// <summary>
        /// Имя для очередного колышка. По кругу: если палаток однажды
        /// станет больше имён, колышки повторятся, но пустыми не будут.
        /// Пустой колышек — это ошибка, которую в сцене никто не заметит,
        /// а повторённое имя видно сразу.
        /// </summary>
        public static string NameFor(int index)
        {
            if (_names.Length == 0) return "";

            int i = index % _names.Length;
            if (i < 0) i += _names.Length;

            return _names[i];
        }
    }
}
