using Sinbinder.Core;

namespace Sinbinder.Gameplay
{
    /// <summary>
    /// Как отряд объясняет вылазку, вернувшись.
    ///
    /// <b>Сколько вернулось, здесь больше не решается.</b> Это считает
    /// <see cref="Expedition"/> настоящим боем: таблица исходов нарушала
    /// правило пролога §2 и, что хуже, расходилась с движком в порядке.
    /// Она делала Жадность лучшим исходом («берёг добычу — сберёг
    /// и людей»), а движок делает её одной из худших: собиратель
    /// отвлекается на добычу и теряет людей. Разбор и замер —
    /// docs/12-BALANCE.md, «Вылазка».
    ///
    /// Осталось объяснение — то, что Карган говорит вслух. Оно переписано
    /// под то, что движок правда делает, и это второй из трёх выходов,
    /// записанных в разборе.
    ///
    /// Правило намеренно без Unity — проверяется стендом.
    /// </summary>
    public static class Homecoming
    {
        /// <summary>
        /// Что предполагает Карган, когда шар наливается красным
        /// (docs/09-PROLOGUE.md §4, сцена 3).
        ///
        /// Догадка растёт из того же греха, что и позднейший
        /// <see cref="Story"/>: доля 3 не имеет права обещать одно,
        /// а эпилог возвращать другое. При этом Карган ошибается —
        /// гаснут не свои отряды, а те, до кого добрались Охотники, —
        /// и потому догадка звучит как догадка, а не как сводка.
        /// </summary>
        public static string Guess(SinType sin, Gender gender)
        {
            // Глаголы прошедшего времени — по роду старшего: Лиску тоже
            // ставят старшей, и «Лиска свернул» читалось бы опиской.
            string P(string he, string she) => Grammar.Pick(gender, he, she);

            switch (sin)
            {
                case SinType.Sloth:
                    return P(Loc.T("опять берёг себя дольше всех"), Loc.T("опять берегла себя дольше всех"));
                case SinType.Wrath:
                    return P(Loc.T("гнал вперёд, не оглядываясь на отставших"), Loc.T("гнала вперёд, не оглядываясь на отставших"));
                case SinType.Pride:
                    return P(Loc.T("не стал отходить, когда стоило"), Loc.T("не стала отходить, когда стоило"));
                case SinType.Greed:
                    return P(Loc.T("свернул за чем-то блестящим"), Loc.T("свернула за чем-то блестящим"));
                case SinType.Envy:
                    return P(Loc.T("не поделил добычу со своими"), Loc.T("не поделила добычу со своими"));
                case SinType.Lust:
                    return P(Loc.T("нашёл, на что отвлечься"), Loc.T("нашла, на что отвлечься"));
                case SinType.Gluttony:
                    return P(Loc.T("встал есть не вовремя"), Loc.T("встала есть не вовремя"));
                default:
                    return P(Loc.T("сделал что-то по-своему"), Loc.T("сделала что-то по-своему"));
            }
        }

        /// <summary>
        /// Чем он это объясняет. Одна фраза, без цифр: игрок и так видит,
        /// сколько их вошло в склеп.
        /// </summary>
        public static string Story(SinType sin, Gender gender)
        {
            string P(string he, string she) => Grammar.Pick(gender, he, she);

            switch (sin)
            {
                // Порядок исходов задаёт движок, а не эта таблица.
                // На равном бою он выстраивает грехи так: хуже всех
                // Уныние, дальше Жадность, Гордыня, Зависть, лучше всех
                // Гнев. Объяснения обязаны читаться в том же порядке —
                // иначе игрок услышит похвалу там, где потерял людей.
                case SinType.Sloth:
                    return P(Loc.T("Он берёг себя, и берёг долго. Ждать его "
                               + "перестали не все и не сразу."),
                             Loc.T("Она берегла себя, и берегла долго. Ждать её "
                               + "перестали не все и не сразу."));
                case SinType.Greed:
                    return P(Loc.T("Он свернул за блеском. Свернули следом, "
                               + "и вернулись оттуда не все."),
                             Loc.T("Она свернула за блеском. Свернули следом, "
                               + "и вернулись оттуда не все."));
                case SinType.Pride:
                    return P(Loc.T("Он не отступил. Отступить пришлось бы первым — "
                               + "а он привык быть последним."),
                             Loc.T("Она не отступила. Отступить пришлось бы первой — "
                               + "а она привыкла быть последней."));
                case SinType.Envy:
                    return Loc.T("Добычу делили дважды. Второй раз — уже без тех, "
                         + "кому она досталась в первый.");
                case SinType.Wrath:
                    return P(Loc.T("Он шёл первым и не давал отстать никому. "
                               + "Отстали всё равно."),
                             Loc.T("Она шла первой и не давала отстать никому. "
                               + "Отстали всё равно."));
                case SinType.Lust:
                    return P(Loc.T("Их задержали. Он не говорит кто."),
                             Loc.T("Их задержали. Она не говорит кто."));
                case SinType.Gluttony:
                    return Loc.T("Припасы кончились раньше дороги.");
                default:
                    return P(Loc.T("Он не рассказывает, и никто не переспрашивает."),
                             Loc.T("Она не рассказывает, и никто не переспрашивает."));
            }
        }
    }
}
