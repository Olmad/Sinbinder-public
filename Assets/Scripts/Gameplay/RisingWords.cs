// Assets/Scripts/Gameplay/RisingWords.cs
using Sinbinder.Core;

namespace Sinbinder.Gameplay
{
    /// <summary>
    /// Что говорит поднятый, открыв глаза.
    ///
    /// Просьба автора от 15 сентября: показывать явно два события —
    /// когда воина создают и когда поднимают того, кто уже умирал.
    /// Про второе он сказал отдельно: «тут память может очень хорошо
    /// сработать». Сработала.
    ///
    /// <b>Две оси, обе из данных, обе без жребия.</b>
    ///
    /// <list type="number">
    /// <item><b>Оболочка</b> — первое, что он о себе узнаёт. Проснуться
    /// камнем и проснуться без ног — разный опыт, и о нём уже написано
    /// в самих телах: «камень знает, что он камень», «бесплотный
    /// не может взять».</item>
    /// <item><b>Память</b> — <see cref="SoulData.HasMemory"/>. У души
    /// с историей есть что терять и о чём тосковать; у пустой нет даже
    /// этого, и её голос — голос человека, которого не с чем сравнить.</item>
    /// <item><b>Заслуженное имя</b> — <see cref="SoulData.EarnedTitle"/>,
    /// добавлено 17 сентября по случаю автора: «Копатель умер,
    /// но Греховод успел забрать душу и снова поднял». Тут я ошибся
    /// вслух: в <c>22-LOOK.md</c> было написано, что титул на поднятии
    /// сказать нельзя, потому что душа его не хранит. Хранить её
    /// научили — за ту же цену, что и память.</item>
    /// </list>
    ///
    /// Различие именно памятью, а не «поднимали ли его раньше»:
    /// признака «уже умирал» в данных нет, а выдумывать его ради реплики
    /// значило бы завести поле, которое никто не заполняет — то самое
    /// «написано, до игры не доведено», которого в проекте и так хватает.
    ///
    /// Жребия нет: одна и та же душа в одном и том же теле скажет
    /// одно и то же.
    /// </summary>
    public static class RisingWords
    {
        /// <summary>
        /// Первая фраза поднятого. Складывается из двух частей, и это
        /// не украшение, а способ не писать таблицу на тридцать пять
        /// клеток: <b>оси умножают, а строки складываются</b>.
        ///
        /// <list type="bullet">
        /// <item><b>Тело</b> — что он о себе узнаёт первым: пять оболочек
        /// на два состояния памяти, десять строк;</item>
        /// <item><b>Ремесло</b> — к чему тянутся руки прежде головы:
        /// семь строк;</item>
        /// <item><b>Имя</b> — если душу взяли вовремя и она донесла титул:
        /// три строки по морали.</item>
        /// </list>
        ///
        /// <b>Имя вытесняет ремесло, а не прибавляется к нему.</b>
        /// Оба отвечают на один и тот же вопрос — что пришло с ним
        /// из прошлой жизни, — и говорить обоими значит превратить
        /// первую фразу в перечисление. Имя громче: ремесло у души
        /// было всегда, титул она нажила. Ремесло молчит только
        /// у титулованных — то есть у считанных, которых успели забрать
        /// свежими; у всех прочих руки говорят как прежде.
        ///
        /// Двадцать написанных строк дают восемьдесят сочетаний,
        /// и ни одно не выпадает жребием.
        /// </summary>
        public static string OnRising(SoulData soul, ShellType shell)
        {
            if (soul == null) return "…";

            string body = Body(shell, soul.HasMemory);

            string tail = string.IsNullOrEmpty(soul.EarnedTitle)
                ? Hands(soul.Trade)
                : Named(soul.EarnedTitle, soul.Moral);

            return string.IsNullOrEmpty(tail) ? body : body + " " + tail;
        }

        /// <summary>
        /// Что говорит имя, которое душа донесла через смерть.
        ///
        /// Ось та же, что на церемонии титула (<c>TitleWords</c>):
        /// мораль, а не жребий. И это не повтор ради симметрии —
        /// человек, принимавший имя гордо, и вспоминает его гордо,
        /// а тяготившийся тяготится им и на второй жизни.
        ///
        /// Титул подставляется именительным падежом, как он и записан
        /// в <c>TitleDatabase</c>: «Костекоп», «Гроза Охотников»,
        /// «Золотые Руки». Фразы построены так, чтобы принять любой
        /// из них без согласования — иначе каждое новое имя в базе
        /// ломало бы речь.
        /// </summary>
        private static string Named(string title, MoralType moral)
        {
            switch (moral)
            {
                // Порочный носил имя как право и требует его обратно.
                case MoralType.Vicious:
                    return $"И звали меня — {title}. Зовите снова.";

                // Праведный помнит, чем имя было оплачено.
                case MoralType.Pious:
                    return $"Меня звали — {title}. За это ещё спросится.";

                // Остальные держатся за имя как за единственное, что цело.
                default:
                    return $"{title}. Это имя я помню лучше своего.";
            }
        }

        /// <summary>Что говорит тело.</summary>
        private static string Body(ShellType shell, bool remembers)
        {
            switch (shell)
            {
                case ShellType.Skeleton:
                    return remembers
                        ? "Руки помнят больше, чем на них осталось."
                        : "Легче. Всё стало легче.";

                case ShellType.Zombie:
                    return remembers
                        ? "Я помню, каким был. Не смотрите на меня."
                        : "Голодно. С самого начала — голодно.";

                case ShellType.Ghost:
                    return remembers
                        ? "Я тянусь — и прохожу насквозь. Всякий раз."
                        : "Меня нет. Но я здесь.";

                case ShellType.Golem:
                    return remembers
                        ? "Мне было тесно и в том теле. В этом — просто тихо."
                        : "Камень. Ну что же. Камень так камень.";

                default:
                    return remembers
                        ? "Я вернулся. И я это помню."
                        : "Я… кто-то. Пока этого хватит.";
            }
        }

        /// <summary>
        /// Что ищут руки. Ремесло тянет душу так же, как тянет оболочка
        /// (<see cref="Trade"/>), и просыпается оно раньше рассудка:
        /// охотник хватается за лук, прежде чем поймёт, что рук у него
        /// уже нет.
        ///
        /// У <c>None</c> руки молчат, и это не пропуск: тело сказало всё,
        /// а прибавлять нечего. Пустая строка здесь — ответ.
        ///
        /// Ремесло уступает заслуженному имени, если оно донеслось:
        /// см. <see cref="OnRising"/>.
        /// </summary>
        private static string Hands(Trade trade)
        {
            switch (trade)
            {
                case Trade.Hunter:    return "Где мой лук?";
                case Trade.Peasant:   return "Земля. Хоть земля на месте.";
                case Trade.Archer:    return "Пальцы ищут тетиву. Нашли.";
                case Trade.Alchemist: return "Склянки... Они ведь разбились, да?";
                case Trade.Mage:      return "Слова ещё здесь. Значит, не всё потеряно.";
                case Trade.Spider:    return "Углы, тени. Я знаю, куда уходить.";
                default:              return "";
            }
        }
    }
}
