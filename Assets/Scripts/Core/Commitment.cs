namespace Sinbinder.Core
{
    /// <summary>
    /// Режим обязательств: сохранение одно, и перезагрузить его нельзя.
    ///
    /// <b>Зачем это именно здесь.</b> Вся игра держится на одном:
    /// воин отказался, и с этим приходится жить. Если после отказа
    /// можно нажать быструю загрузку, отказ не стоит ничего —
    /// он становится помехой, которую обходят клавишей, а не событием.
    /// Движок при этом продолжает работать безупречно и совершенно
    /// впустую.
    ///
    /// Поэтому режим не «повышенная сложность». Это режим, в котором
    /// игра работает так, как задумана, а обычный — тот, где игроку
    /// разрешено от неё отдохнуть.
    ///
    /// Как в Rimworld: игра пишет сама, в названные моменты, в один
    /// и тот же файл. Быстрое сохранение не нужно (оно и так есть
    /// всегда), быстрая загрузка запрещена.
    ///
    /// Правило без Unity — проверяется стендом.
    /// </summary>
    public static class Commitment
    {
        private static bool _on;

        /// <summary>Идёт ли ответственная игра.</summary>
        public static bool On => _on;

        /// <summary>
        /// Включить или выключить. Меняется только между партиями:
        /// снять обязательство посреди игры — то же самое, что
        /// не брать его вовсе.
        /// </summary>
        public static void Set(bool on) => _on = on;

        /// <summary>Можно ли сейчас грузить по своей воле.</summary>
        public static bool CanLoad => !_on;

        /// <summary>
        /// Что сказать, когда нажали загрузку в ответственной игре.
        ///
        /// Не «нельзя», а почему: запрет без причины читается как
        /// поломка, а этот запрет — половина замысла.
        /// </summary>
        public static string WhyNoLoad =>
            "Вы взяли на себя обязательство. Переиграть нельзя — "
          + "в этом и был уговор.";

        /// <summary>Названия режимов для меню. Без цифр, как и всё здесь.</summary>
        public static string Describe(bool on)
        {
            return on
                ? "С обязательством: одно сохранение, переиграть нельзя"
                : "Свободно: сохраняйтесь и грузитесь когда угодно";
        }

        public static void Reset() => _on = false;
    }
}
