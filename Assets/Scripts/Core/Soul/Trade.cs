// Assets/Scripts/Core/Soul/Trade.cs
namespace Sinbinder.Core
{
    /// <summary>
    /// Ремесло души: кем она была до того, как её собрали.
    ///
    /// Автор называет это профессией и хочет видеть её в имени:
    /// «Гертон Крестьянин», «Сквип Паук». Порядок слов обратный титулу —
    /// профессия идёт после имени, титул перед, — и потому превращение
    /// «Гертон Крестьянин» → «Костекоп Гертон» читается без объяснений.
    ///
    /// <b>Это механика, а не подпись.</b> Решение автора от 11 сентября.
    /// </summary>
    public enum Trade
    {
        None = 0,
        Hunter = 1,
        Peasant = 2,
        Archer = 3,
        Alchemist = 4,
        Mage = 5,
        Spider = 6,
    }

    /// <summary>
    /// Что ремесло делает с душой.
    ///
    /// Не прибавка к действию сбоку, а <b>смещение спектров</b> — тем же
    /// приёмом, каким на душу действует оболочка (<c>ShellData</c>,
    /// docs/08-FLOOR.md §3.2: «плоть тянет душу на себя»). Ремесло тянет
    /// её точно так же: охотник терпелив, потому что иначе не выживают
    /// в засаде, а крестьянин не рвётся в драку, потому что не его дело.
    ///
    /// Почему именно так, а не надбавками к действиям: правило проекта
    /// гласит, что механика обязана проходить через личность, иначе это
    /// вторая игра сбоку. Смещение спектров проходит через неё
    /// по построению — оно и есть личность. Дальше голосуют те же
    /// тринадцать модулей, ничего не зная ни о каких профессиях.
    ///
    /// Побочное следствие, ради которого стоило: <see cref="ClassData"/>
    /// с его <c>attackModifier</c> и <c>defenseModifier</c> остаётся
    /// не нужен. Он написан, не подключён ни к чему и ни одного ассета
    /// под него не создано — седьмой случай «написано, звена нет».
    /// Подключать его значило бы завести вторую правду о воине.
    ///
    /// Правило без Unity — проверяется стендом.
    /// </summary>
    public static class Trades
    {
        /// <summary>Порядок как в <see cref="SinType"/>: Жадность, Гордыня,
        /// Гнев, Зависть, Похоть, Чревоугодие, Уныние.</summary>
        private static readonly float[][] Bias =
        {
            //           Жад   Горд   Гнев   Зав   Похоть  Чрево  Уныние
            new[] {   0f,    0f,    0f,    0f,    0f,    0f,    0f },  // нет ремесла

            // Охотник: в засаде выживает терпеливый, и он это знает о себе.
            new[] {  -5f,   10f,  -18f,   -5f,    0f,    0f,  -10f },

            // Крестьянин: не его дело — драться. Зато своё он не отдаст.
            new[] {  12f,  -18f,  -10f,    5f,    0f,    8f,   20f },

            // Лучник: бьёт издали, и оттого не лезет вперёд.
            new[] {  -5f,   12f,  -22f,    0f,    0f,   -5f,    0f },

            // Алхимик: тащит всё, что может пригодиться, и завидует чужому.
            new[] {  22f,    0f,  -15f,   12f,   -8f,    0f,    0f },

            // Маг: ставит себя отдельно от прочих. Потому и один.
            new[] {  -8f,   25f,    0f,   15f,  -12f,  -10f,    0f },

            // Паук: душа животного в человеческом теле (15-AFTER.md §6).
            // Своих у него нет, добыча есть, и человеческого в нём мало.
            new[] {   0f,  -20f,   10f,    0f,  -30f,   25f,    0f },
        };

        private static readonly string[] Names =
        {
            "", "Охотник", "Крестьянин", "Лучник", "Алхимик", "Маг", "Паук",
        };

        /// <summary>Как ремесло зовут. Пусто — ремесла нет.</summary>
        public static string Name(Trade trade)
        {
            int i = (int)trade;
            return i >= 0 && i < Names.Length ? Names[i] : "";
        }

        /// <summary>
        /// Насколько ремесло тянет эту шкалу. Плюс — к греху, минус —
        /// к добродетели того же спектра.
        /// </summary>
        public static float Pull(Trade trade, SinType spectrum)
        {
            int t = (int)trade;
            int s = (int)spectrum;

            if (t < 0 || t >= Bias.Length) return 0f;
            if (s < 0 || s >= SoulData.SpectrumCount) return 0f;

            return Bias[t][s];
        }

        /// <summary>
        /// Приложить ремесло к душе. Зовётся один раз, при создании:
        /// ремесло — то, кем душа была, а не то, чем её можно натереть
        /// по дороге. Дважды приложенное удвоило бы наклон.
        /// </summary>
        public static void Apply(SoulData soul, Trade trade)
        {
            if (soul == null || trade == Trade.None) return;

            for (int s = 0; s < SoulData.SpectrumCount; s++)
            {
                float pull = Pull(trade, (SinType)s);
                if (pull != 0f) soul.Change((SinType)s, pull);
            }
        }
    }
}
