namespace Sinbinder.Core
{
    public enum ShellType
    {
        Skeleton = 0,
        Zombie = 1,
        Ghost = 2,
        Golem = 3,

        /// <summary>
        /// Живое тело: люди, которые ещё не умерли. Охотники и инквизиторы.
        ///
        /// Заведено 14 сентября по слову автора: «охотники — люди». До этого
        /// они ходили в оболочке зомби, и это была не косметика: оболочка
        /// тянет душу (зомби +25 Чревоугодия), а движок считал их нежитью —
        /// перки «против нежити» срабатывали на живых людей.
        ///
        /// Номер в конце: перечисление сериализуется числом, и сдвинуть
        /// существующие значения значило бы молча переписать сцены.
        /// </summary>
        Living = 4,
    }

    /// <summary>Что с оболочкой можно делать. Одно место на правило.</summary>
    public static class ShellKinds
    {
        /// <summary>
        /// Можно ли вселить в неё душу. В живое тело — нет: у него своя
        /// душа, и устройство связывания работает с мёртвыми. Экран выбора
        /// тела и стол тел в склепе спрашивают здесь, а не держат список сами.
        /// </summary>
        public static bool Bindable(ShellType type) => type != ShellType.Living;
    }
}
