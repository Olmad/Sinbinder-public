namespace Sinbinder.Core
{
    /// <summary>
    /// Как воина зовут на экране.
    ///
    /// Замысел автора: пока титула нет, после имени стоит ремесло —
    /// «Гертон Крестьянин», «Сквип Паук». Заработал титул — и порядок
    /// слов переворачивается: «Костекоп Гертон».
    ///
    /// Приём держится сам, без объяснений. Игрок видит, что слово
    /// переехало вперёд, и понимает, что оно теперь другого сорта:
    /// ремесло у души было всегда, титул она нажила при нём. Ни одной
    /// подсказки для этого не нужно — нужен только порядок слов.
    ///
    /// <b>Порядок старшинства</b> — решение автора 16 октября: «отображаться
    /// должно приоритетное имя по принципу Легендарный титул > обычный
    /// титул > профессии». Ремесло при этом не пропадает: оно в душе,
    /// в облике и в первых словах поднятого — «Крестьянин» хранится как
    /// предыстория, просто не в строке имени.
    ///
    /// <b>Прозвище — часть имени.</b> «Марга Копатель», «Вейн Тихий»,
    /// «Карган Старый Ворон» уже несут второе слово, и ремесло после него —
    /// «Марга Копатель Крестьянин» — это три слова там, где человек один.
    /// Тот же довод стоял у Каргана с сентября («Старый Ворон Охотник —
    /// одно, сказанное трижды»), теперь он правило: ремесло дописывается
    /// только к имени из одного слова — «Лиска Лучник», «Ансельм Ловчий».
    ///
    /// Правило без Unity — проверяется стендом.
    /// </summary>
    public static class Naming
    {
        /// <summary>
        /// Полное имя. <paramref name="legend"/> и <paramref name="title"/> —
        /// то, что сложил <c>TitleManager</c> в виде «Титул Имя»; пусто —
        /// такого нет. Легендарное старше обычного: обычный титул можно
        /// заработать и после легенды (он сильнее по счёту деяний), но
        /// легенду он не заслоняет.
        /// </summary>
        public static string Full(string name, Trade trade, string legend, string title)
        {
            if (!string.IsNullOrEmpty(legend)) return legend;
            if (!string.IsNullOrEmpty(title)) return title;
            if (string.IsNullOrEmpty(name) || name.IndexOf(' ') >= 0) return name;

            string craft = Trades.Name(trade);
            return string.IsNullOrEmpty(craft) ? name : name + " " + craft;
        }
    }
}
