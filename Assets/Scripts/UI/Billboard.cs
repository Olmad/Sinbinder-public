// Assets/Scripts/UI/Billboard.cs
using UnityEngine;

namespace Sinbinder.UI
{
    /// <summary>
    /// Держать объект развёрнутым к камере — и не пускать его в объектив.
    ///
    /// Нужен надголовному интерфейсу: холст в мировом пространстве стоит
    /// как поставлен, и значок намерения виден с одной стороны, а с другой
    /// исчезает. Для кадра, которым игра продаётся, это неприемлемо.
    ///
    /// Холст этот — метр шириной: с тактической высоты он в плечо воину,
    /// а у самой камеры — плашка поперёк кадра. Наезд ставит камеру в двух
    /// метрах от говорящего, первое лицо — на уровень глаз среди отряда,
    /// и полоса соседа закрывала пол-экрана (кадр «Греховод пал»,
    /// 26 сентября). Поэтому вблизи камеры надголовное гаснет.
    ///
    /// Разворот и угасание — чистая косметика и на решения не влияют никак,
    /// поэтому правило повторяемости их не касается.
    /// </summary>
    public class Billboard : MonoBehaviour
    {
        /// <summary>
        /// Ближе этого к камере надголовного не видно вовсе: полоса соседа
        /// в пяти метрах от объектива — уже шестая часть кадра наезда.
        /// </summary>
        public const float Near = 6f;

        /// <summary>
        /// Отсюда и дальше — целиком. Тактическая камера висит на двадцати
        /// двух метрах, полоса — на двух с половиной: в бою она не гаснет
        /// никогда, и зум (он сужает поле зрения, а не подвозит камеру)
        /// этого не меняет.
        /// </summary>
        public const float Far = 10f;

        private Transform _eye;
        private CanvasGroup _group;

        void Start()
        {
            _group = GetComponent<CanvasGroup>();
            if (_group == null) _group = gameObject.AddComponent<CanvasGroup>();
            Retarget();
        }

        /// <summary>Найти камеру заново. Нужен после возврата из пула.</summary>
        public void Retarget()
        {
            var cam = Camera.main;
            _eye = cam != null ? cam.transform : null;
        }

        /// <summary>
        /// Сколько надголовного видно, если до камеры столько метров:
        /// ноль у объектива, целиком — издали.
        /// </summary>
        public static float Presence(float distance) => Mathf.InverseLerp(Near, Far, distance);

        void LateUpdate()
        {
            if (_eye == null) { Retarget(); return; }

            // Смотрим в ту же сторону, куда смотрит камера, а не на неё:
            // так надписи над разными воинами остаются параллельными
            // и строй не разъезжается веером.
            transform.rotation = _eye.rotation;

            // Гасим по расстоянию, а не по тому, кто держит камеру. Флаг
            // наезда снимает RestoreCamera, а его могут и не позвать — воин
            // погиб, сцену выгрузили, — и полосы пропали бы до конца игры.
            // Расстояние застрять не может, и первое лицо оно ловит тоже.
            // Туман прячет чужих своим рычагом (Canvas.enabled), этот ему
            // не мешает.
            if (_group != null)
                _group.alpha = Presence(Vector3.Distance(_eye.position, transform.position));
        }
    }
}
