"""
Голем — глыбы на костях.

«Камень не завидует. Камень знает, что он камень.» Прежний голем
(`bodies.py`, до 1 октября) был ящиками: ровные грани читались изделием,
а не камнем. Здесь каждая глыба — брусок поля расстояний со скруглённым
ребром и сколами по углам: сколы срезаны наклонными брусками, а не
жребием — один и тот же голем при каждой сборке (CLAUDE.md, «ничего
случайного»).

Камень не гнётся: каждая глыба жёстко висит на своей кости, между
глыбами — щели. Голем держится не мышцей, а тем, что в него вложили,
и щель это и показывает. Трещины красятся сами — по зажатости поля
(`anatomy.part`): чем глубже щель, тем темнее; глаза горят в щели под
надбровьем (материал «Глаз», его красит SinEyes).
"""

import math

import anatomy
from sdf import Brick, Egg, Field, turn

# Материалы — номера из `bodies.SHELLS`: камень, камень стёртый, трещина,
# глаз. У `anatomy.part` те же места: кость, тень, пустота, глаз.
STONE, WORN, CRACK, EYE = 0, 1, 2, 3


def chipped(f, centre, half, edge, yaw=0.0, chips=(), k=0.0):
    """
    Глыба: тёсаный камень — куб с притуплёнными рёбрами (сверхэллипсоид
    степени 6), чуть повёрнутый, со сколами по углам. Ровный брусок
    (первый заход 1 октября) читался кубиком из игрушки, круглый
    сверхэллипсоид (второй) — подушкой. chips — углы, с которых сбит
    камень: (±1, ±1, ±1) — какой угол, и глубина.

    Наклон каждой глыбы — от её же места (а не жребий): глыбы не стоят
    по линейке, и голем при этом один и тот же при каждой сборке.
    """
    hx, hy, hz = (h + edge * 0.5 for h in half)
    cx, cy, cz = centre
    tilt = math.sin(cx * 41.0 + cz * 17.0) * 4.0
    rot = turn(yaw=yaw + tilt * 0.5, pitch=tilt * 0.6, roll=-tilt * 0.4)
    f.add(Egg(centre, (hx, hy, hz), rot=rot, power=6.0), k=k)
    for (sx, sy, sz), depth in chips:
        corner = (cx + sx * hx * 0.95, cy + sy * hy * 0.95, cz + sz * hz * 0.95)
        f.cut(Egg(corner, (depth * 1.3, depth * 1.3, depth), power=6.0,
                  rot=turn(yaw=45.0, pitch=30.0 * sz, roll=30.0 * sy)), k=0.002)


def crack(f, a, b, width):
    """
    Трещина — наклонный рез поперёк глыбы. Шире полутора сантиметров:
    узкая (первый заход) пропадала при прореживании, оставляя косые грани.
    """
    mid = tuple((x + y) * 0.5 for x, y in zip(a, b))
    dx, dz = b[0] - a[0], b[2] - a[2]
    length = math.hypot(dx, dz) * 0.5
    angle = math.degrees(math.atan2(dz, dx))
    f.cut(Brick(mid, (length, 0.030, max(width, 0.0075)), 0.0, rot=turn(roll=-angle)), k=0.002)


def golem(b, p):
    """Голем: таз, корпус, голова без шеи, плечи-валуны, руки-глыбы, ноги-столбы."""
    hip, knee, ankle = p["hip"], p["knee"], p["ankle"]
    waist, chest, sh = p["waist"], p["chest"], p["shoulder"]
    sx, el, wr, fg = p["shoulder_x"], p["elbow"], p["wrist"], p["finger"]
    lx, kx = p["leg_x"], p.get("knee_x", p["leg_x"])
    skull = p["skull"]

    # Корпус — на одной кости: камень не сгибается (как и прежде).
    f = Field()
    chipped(f, (0, 0.004, chest + 0.030), (0.120, 0.074, 0.075), 0.016, yaw=2.0,
            chips=[((1, -1, 1), 0.030), ((-1, 1, 1), 0.026), ((-1, -1, -1), 0.024)])
    chipped(f, (0, 0.010, waist + 0.010), (0.098, 0.064, 0.050), 0.014, yaw=-3.0,
            chips=[((1, 1, -1), 0.024), ((-1, -1, 1), 0.020)], k=0.006)
    chipped(f, (0, 0.012, sh + 0.006), (0.150, 0.064, 0.030), 0.014,
            chips=[((1, -1, 1), 0.028), ((-1, 1, 1), 0.024)], k=0.008)
    crack(f, (0.030, -0.080, chest + 0.090), (0.070, -0.080, chest - 0.020), 0.004)
    crack(f, (-0.090, -0.080, chest + 0.040), (-0.050, -0.080, chest - 0.010), 0.0035)
    anatomy.part(b, f, 0.0026, "Spine", keep=3000, reach=0.014, deep=0.55, dim=0.32)

    f = Field()
    chipped(f, (0, 0.006, hip + 0.012), (0.104, 0.066, 0.046), 0.012,
            chips=[((1, -1, -1), 0.022), ((-1, 1, -1), 0.020)])
    anatomy.part(b, f, 0.0030, "Hips", keep=700, reach=0.012)

    # Голова сидит на плечах, без шеи; надбровье нависает, глаза — в щели.
    f = Field()
    chipped(f, (0, 0.012, skull - 0.004), (0.060, 0.066, 0.052), 0.012,
            chips=[((1, 1, 1), 0.024), ((-1, -1, 1), 0.016)])
    chipped(f, (0, -0.050, skull + 0.016), (0.062, 0.020, 0.016), 0.006, k=0.006)
    f.cut(Brick((0, -0.062, skull - 0.004), (0.046, 0.016, 0.009), 0.003), k=0.002)
    anatomy.part(b, f, 0.0020, "Head", keep=900, reach=0.010, deep=0.62, dim=0.38)
    for s in (1, -1):
        anatomy.pill(b, "Head", (s * 0.024, -0.052, skull - 0.004), (0.012, 0.004, 0.0055), mat=EYE,
                     segs=10, rings=6, square=0.6)

    for s, tag in ((1, "Left"), (-1, "Right")):
        # Плечо — валун поверх плеча.
        f = Field()
        f.add(Egg((s * (sx - 0.020), 0.008, sh + 0.024), (0.070, 0.068, 0.058)))
        f.cut(Brick((s * (sx + 0.040), -0.060, sh + 0.070), (0.030, 0.030, 0.030), 0.003,
                    rot=turn(yaw=30.0, pitch=25.0)), k=0.002)
        anatomy.part(b, f, 0.0026, tag + "Shoulder", keep=500, reach=0.012)

        # Плечо руки и предплечье — глыбы вдоль X, предплечье толще к кулаку.
        f = Field()
        chipped(f, (s * (sx + el) * 0.5, 0.0, sh), (abs(el - sx) * 0.5 - 0.010, 0.046, 0.046), 0.012,
                chips=[((s, -1, 1), 0.018), ((-s, 1, -1), 0.016)])
        anatomy.part(b, f, 0.0026, tag + "UpperArm", keep=450, reach=0.012)

        f = Field()
        chipped(f, (s * (el + wr) * 0.5, 0.0, sh - 0.004), (abs(wr - el) * 0.5 - 0.008, 0.052, 0.054), 0.012,
                chips=[((s, 1, 1), 0.020), ((-s, -1, -1), 0.016)])
        crack(f, (s * (el + 0.020), -0.054, sh + 0.030), (s * (el + 0.060), -0.054, sh - 0.020), 0.003)
        anatomy.part(b, f, 0.0026, tag + "LowerArm", keep=450, reach=0.012)

        # Кулак — глыба с бороздами пальцев.
        f = Field()
        chipped(f, (s * (wr + fg) * 0.5 + s * 0.006, 0.0, sh - 0.006), (abs(fg - wr) * 0.5 + 0.004, 0.054, 0.054),
                0.014, chips=[((s, -1, 1), 0.016)])
        for dy in (-0.026, 0.0, 0.026):
            f.cut(Brick((s * (fg + 0.010), dy, sh - 0.006), (0.020, 0.0025, 0.060), 0.0), k=0.002)
        anatomy.part(b, f, 0.0024, tag + "Hand", keep=400, reach=0.010)

        # Ноги — столбы, стопа — плита.
        f = Field()
        chipped(f, (s * lx, 0.0, (hip + knee) * 0.5), (0.062, 0.060, (hip - knee) * 0.5 - 0.012), 0.012,
                chips=[((s, -1, -1), 0.020), ((-s, 1, 1), 0.018)])
        anatomy.part(b, f, 0.0028, tag + "UpperLeg", keep=450, reach=0.012)

        f = Field()
        chipped(f, (s * kx, 0.0, (knee + ankle) * 0.5 + 0.010), (0.058, 0.056, (knee - ankle) * 0.5 - 0.010),
                0.012, chips=[((s, 1, 1), 0.018), ((-s, -1, -1), 0.016)])
        anatomy.part(b, f, 0.0028, tag + "LowerLeg", keep=450, reach=0.012)

        f = Field()
        chipped(f, (s * kx, -0.026, 0.030), (0.066, 0.090, 0.030), 0.010,
                chips=[((s, -1, 1), 0.016), ((-s, -1, 1), 0.014)])
        anatomy.part(b, f, 0.0026, tag + "Foot", keep=400, reach=0.010)
