def legs(b, p):
    """
    Бедренная (головка во впадине таза, шейка, большой вертел, стержень,
    мыщелки), большеберцовая с малоберцовой и надколенником, стопа
    и пальцы.
    """
    hip, knee, ankle, lx = p["hip"], p["knee"], p["ankle"], p["leg_x"]
    kx = p.get("knee_x", lx)
    for s, tag in ((1, "Left"), (-1, "Right")):
        f = Field()
        f.add(Ball((s * lx, 0.0, hip), 0.0135))
        f.add(Bar((s * lx, 0.0, hip), (s * (lx + 0.018), 0.001, hip - 0.013), 0.0075, 0.0085), k=0.004)
        f.add(Egg((s * (lx + 0.022), 0.004, hip - 0.010), (0.0095, 0.0115, 0.0140)), k=0.005)
        f.add(Egg((s * (lx + 0.006), 0.008, hip - 0.036), (0.0055, 0.0060, 0.0065)), k=0.004)
        f.add(Bar((s * (lx + 0.016), 0.0, hip - 0.020), (s * (kx + 0.002), -0.002, knee + 0.022),
                  0.0098, 0.0088), k=0.008)
        for side in (1, -1):
            f.add(Egg((s * (kx + side * 0.0115), 0.003, knee + 0.007), (0.0105, 0.0140, 0.0115)), k=0.006)
        f.cut(Egg((s * kx, 0.010, knee + 0.002), (0.0035, 0.0070, 0.0060)), k=0.002)
        part(b, f, 0.0014, tag + "UpperLeg", keep=1000, reach=0.008)

        f = Field()
        f.add(Egg((s * kx, 0.002, knee - 0.009), (0.0195, 0.0155, 0.0070)))
        f.add(Egg((s * kx, -0.010, knee - 0.022), (0.0060, 0.0050, 0.0080)), k=0.005)
        f.add(Bar((s * kx, 0.0, knee - 0.016), (s * (kx - 0.002), 0.003, ankle + 0.012), 0.0090, 0.0068),
              k=0.008)
        f.add(Egg((s * (kx - 0.009), 0.003, ankle + 0.004), (0.0065, 0.0085, 0.0100)), k=0.005)
        # Малоберцовая — снаружи и сзади, тонкая, с головкой и лодыжкой.
        out = kx + 0.018
        f.add(Egg((s * out, 0.008, knee - 0.020), (0.0055, 0.0060, 0.0060)), k=0.003)
        f.add(Bar((s * out, 0.008, knee - 0.022), (s * (out + 0.002), 0.006, ankle + 0.006), 0.0040, 0.0036),
              k=0.004)
        f.add(Egg((s * (out + 0.002), 0.006, ankle - 0.002), (0.0050, 0.0070, 0.0100)), k=0.004)
        # Надколенник — на голени: при сгибе он идёт с ней, а не с бедром.
        f.add(Egg((s * kx, -0.0175, knee + 0.010), (0.0085, 0.0045, 0.0105)), k=0.0)
        part(b, f, 0.0013, tag + "LowerLeg", keep=1100, reach=0.008)

        foot(b, tag, s, kx, ankle)


def foot(b, tag, s, x, ankle):
    """
    Стопа: таранная и пяточная, предплюсна, пять плюсневых — на кости
    Foot; фаланги — на Toes. Большой палец внутрь (к середине тела).
    """
    # Свод, а не доска: таранная сверху под голенью, пятка уходит назад
    # и вниз, плюсна спускается от предплюсны к подушечкам.
    f = Field()
    f.add(Egg((s * x, 0.004, ankle - 0.012), (0.0110, 0.0140, 0.0085)))
    f.add(Egg((s * (x + 0.003), 0.024, 0.018), (0.0105, 0.0210, 0.0150)), k=0.005)
    f.add(Egg((s * (x + 0.004), 0.038, 0.012), (0.0085, 0.0080, 0.0100)), k=0.004)
    f.add(Egg((s * x, -0.016, 0.034), (0.0165, 0.0120, 0.0100)), k=0.005)

    rays = [(-0.0135, 0.0052), (-0.0060, 0.0036), (0.0005, 0.0034), (0.0065, 0.0032), (0.0120, 0.0032)]
    for off, r in rays:
        f.add(Bar((s * (x + off * 0.7), -0.024, 0.033), (s * (x + off), -0.066, 0.008), r * 1.1, r),
              k=0.002)
        f.add(Egg((s * (x + off), -0.066, 0.008), (r * 1.25, r * 1.35, r * 1.25)), k=0.002)
    part(b, f, 0.0010, tag + "Foot", keep=1100, reach=0.006)

    f = Field()
    for n, (off, r) in enumerate(rays):
        length = 0.030 if n == 0 else 0.024 - 0.002 * n
        a = (s * (x + off), -0.068, 0.008)
        m = (s * (x + off * 1.05), -0.068 - length * 0.55, 0.006)
        e = (s * (x + off * 1.08), -0.068 - length, 0.005)
        f.add(chain([a, m, e], [r * 1.05, r * 0.95, r * 0.80]), k=0.0015)
    part(b, f, 0.0009, tag + "Toes", keep=500, reach=0.004)


def skeleton(b, p):
    """Весь скелет: череп, позвоночник, клетка, таз, плечи, руки, ноги."""
    skull(b, p)
    neck(b, p)
    ribcage(b, p)
    lumbar(b, p)
    pelvis(b, p)
    shoulders(b, p)
    arms(b, p)
    legs(b, p)
