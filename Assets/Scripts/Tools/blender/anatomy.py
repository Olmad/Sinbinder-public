def thoracic(i):
    """Высота, отступ назад, радиус и полувысота тела i-го грудного (0 — первый)."""
    z = 0.842 - i * 0.0128
    y = 0.024 + 0.010 * math.sin(math.pi * i / 11.0)
    return z, y, 0.0072 + 0.0023 * i / 11.0, 0.0046 + 0.0010 * i / 11.0


