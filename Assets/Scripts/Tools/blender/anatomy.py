def sternum_y(z):
    """Передняя линия грудины: верх дальше назад, низ вперёд (наклон 9°)."""
    return -0.047 - 0.158 * (0.8255 - z)


def ribcage(b, p):
    """
    Клетка на кости Chest: двенадцать грудных позвонков, двенадцать пар
    рёбер, хрящи и грудина. Высота у эталона — 0,693…0,852 роста;
    прежняя клетка стояла на семь сотых ниже и висела под плечами.
    """
    f = Field()
    cartilage = []

    for i in range(12):
        z, y, body, half = thoracic(i)
        vertebra(f, z, y, body, half, spine=0.020 if i < 10 else 0.016,
                 tilt=0.010 if i < 10 else 0.004, wings=0.0150)

    ends = {}
    for i, (wide, deep, drop, stop, r) in enumerate(RIBS):
        z, y, body, _ = thoracic(i)
        for s in (1, -1):
            pts = [(s * body * 0.8, y + body * 0.4, z + 0.001), (s * 0.019, y + 0.015, z - 0.0005)]
            steps = 9
            for k in range(steps):
                phi = 0.45 + (stop - 0.45) * k / (steps - 1)
                pts.append((s * wide * math.sin(phi), -0.002 + deep * math.cos(phi),
                            z - drop * (1.0 - math.cos(phi)) * 0.5))
            radii = [r * 0.9, r] + [r] * (steps - 2) + [r * 0.95, r * (0.7 if i >= 10 else 0.95)]
            f.add(chain(pts, radii[:len(pts)]), k=0.0025)
            ends[(i, s)] = pts[-1]

    # Хрящи: верхние семь — к грудине, восьмой-десятый — к хрящу выше,
    # складываясь в рёберную дугу; одиннадцатое и двенадцатое висят.
    to_sternum = [0.8260, 0.8140, 0.8000, 0.7870, 0.7740, 0.7620, 0.7520]
    for s in (1, -1):
        for i, zs in enumerate(to_sternum):
            a = ends[(i, s)]
            c = (s * 0.0095, sternum_y(zs) + 0.002, zs)
            mid = ((a[0] + c[0]) * 0.5, (a[1] + c[1]) * 0.5 - 0.002, (a[2] + c[2]) * 0.5)
            bars = chain([a, mid, c], [0.0030, 0.0028, 0.0026])
            cartilage += bars
            f.add(bars, k=0.002)
        prev = ends[(6, s)]
        joint = None
        for i in (7, 8, 9):
            a = ends[(i, s)]
            if joint is None:
                c7 = (s * 0.0095, sternum_y(0.752) + 0.002, 0.752)
                joint = (prev[0] * 0.45 + c7[0] * 0.55, prev[1] * 0.45 + c7[1] * 0.55 - 0.002,
                         prev[2] * 0.45 + c7[2] * 0.55)
            bar = Bar(a, joint, 0.0028, 0.0026)
            cartilage.append(bar)
            f.add(bar, k=0.002)
            joint = ((a[0] + joint[0]) * 0.5, (a[1] + joint[1]) * 0.5, (a[2] + joint[2]) * 0.5)

    # Грудина: рукоятка, тело, мечевидный отросток — с наклоном.
    tilt = turn(pitch=-9.0)
    f.add(Brick((0, sternum_y(0.8255), 0.8255), (0.0100, 0.0022, 0.0066), 0.0020, rot=tilt), k=0.003)
    f.add(Brick((0, sternum_y(0.7870), 0.7870), (0.0060, 0.0020, 0.0300), 0.0018, rot=tilt), k=0.003)
    f.add(Bar((0, sternum_y(0.756), 0.756), (0, sternum_y(0.742), 0.742), 0.0024, 0.0014), k=0.002)

    part(b, f, 0.0013, "Chest", keep=6500, reach=0.008, shade=cartilage)


