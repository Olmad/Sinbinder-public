# Хват: где в кулаке лежит рукоять — от запястья по кости кисти (x),
# ниже ладони (z), ось рукояти — вперёд (−Y), радиус рукояти.
# Оружие (`weapons.py`) садится сюда же: кулак и рукоять считаются
# от одних чисел и потому сходятся.
GRIP_AHEAD = 0.050
GRIP_BELOW = 0.018
GRIP_R = 0.0105


def grip(p, side):
    """Середина рукояти в кулаке, в пространстве тела."""
    return (side * (p["wrist"] + GRIP_AHEAD), 0.0, p["shoulder"] - GRIP_BELOW)


def hand(b, bone, s, wr, fg, z):
    """
    Кисть, сжатая вокруг рукояти: запястье, пять пястных, фаланги
    обхватывают её сверху вниз и назад, большой палец ложится поверх.

    Кулак, а не раскрытая ладонь: воин держит оружие, щит или древко
    (27 сентября — «оружием займись» после скелета). Отдельных костей
    у пальцев в арматуре нет, так что кисть сжата раз и навсегда —
    с пустыми руками это читается сжатыми кулаками бойца, а не
    поломкой. Раскрытой кисти эталона нечего держать.
    """
    f = Field()
    gx, gz = wr + GRIP_AHEAD, z - GRIP_BELOW
    wrap = GRIP_R + 0.0045

    # Запястье и пясть — от запястья к костяшкам над рукоятью.
    f.add(Egg((s * (wr + 0.012), 0.0, z), (0.0100, 0.0135, 0.0060)))
    # (поперёк, длина фаланг, радиус) — от указательного к мизинцу.
    fingers = [(-0.0120, (0.024, 0.015, 0.012), 0.0030),
               (-0.0040, (0.026, 0.017, 0.012), 0.0031),
               (0.0040, (0.024, 0.016, 0.011), 0.0029),
               (0.0112, (0.019, 0.012, 0.010), 0.0026)]
    for y, phal, r in fingers:
        knuckle = (s * gx, y, gz + wrap)
        f.add(Bar((s * (wr + 0.018), y * 0.45, z), knuckle, r * 1.05, r * 1.15), k=0.002)
        f.add(Ball(knuckle, r * 1.25), k=0.0015)

        # Фаланги — по кругу вокруг рукояти: через верх, наружу, вниз
        # и под неё, к ладони. Угол — по длине дуги.
        angle, at = math.pi / 2.0, knuckle
        for n, length in enumerate(phal):
            angle -= length / wrap
            nxt = (s * (gx + math.cos(angle) * wrap), y, gz + math.sin(angle) * wrap)
            f.add(Bar(at, nxt, r * (1.0 - 0.10 * n), r * (0.92 - 0.10 * n)), k=0.0015)
            at = nxt

    # Большой палец: от основания ладони вперёд и вниз, поверх
    # указательного — как держат меч.
    thumb = [(s * (wr + 0.012), -0.011, z - 0.002), (s * (wr + 0.030), -0.021, z - 0.010),
             (s * (gx - 0.006), -0.021, gz - 0.006), (s * (gx + 0.004), -0.017, gz - wrap + 0.001)]
    f.add(chain(thumb, [0.0036, 0.0034, 0.0030, 0.0025]), k=0.0015)
    part(b, f, 0.0008, bone, keep=1300, reach=0.004)


