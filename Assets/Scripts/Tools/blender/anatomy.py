def shell(f, low, high, bulge, side, r, k, rows=3):
    """
    Изогнутая пластина между двумя кривыми: нижней (low) и верхней
    (high), с выпуклостью bulge наружу посередине. Крыло таза у эталона —
    раковина: снаружи выпуклая, изнутри — ямка. Плоский веер из
    треугольников читался бумажным.
    """
    cols = len(low)

    def point(i, j):
        v = j / rows
        a, c = np.asarray(low[i], dtype=np.float64), np.asarray(high[i], dtype=np.float64)
        p = a + (c - a) * v
        u = i / (cols - 1)
        p[0] += side * bulge * math.sin(math.pi * v) * math.sin(math.pi * u)
        return tuple(p)

    for i in range(cols - 1):
        for j in range(rows):
            a, b2, c, d = point(i, j), point(i + 1, j), point(i + 1, j + 1), point(i, j + 1)
            f.add(Plate([a, b2, c], r), k=k)
            f.add(Plate([a, c, d], r), k=k)


def pelvis(b, p):
    """
    Таз на кости Hips: крестец с копчиком сзади, два крыла подвздошной
    кости раковиной от вертлужной впадины к гребню, седалищные бугры,
    лобковые дуги вокруг запирательного отверстия. Впадина стоит ровно
    там, где арматура держит бедро, и открыта наружу: головка бедра
    видна и поворачивается в ней.

    Первый заход (27 сентября) читался грубо: крылья — плоские веера,
    крестец — щит отдельно от крыльев, лобковые дуги — проволока,
    впадины — закрытые шары вокруг головки. Этот — по крупным планам
    эталона.
    """
    hip, lx = p["hip"], p["leg_x"]
    f = Field()

    # Крестец — изогнутый клин, основание сверху, крылья-«уши» к подвздошным.
    f.add(Plate([(-0.026, 0.020, 0.600), (0.026, 0.020, 0.600),
                 (0.009, 0.040, 0.538), (-0.009, 0.040, 0.538)], 0.0055))
    f.add(Disc((0, 0.016, 0.5985), 0.0110, 0.0035, 0.0015), k=0.003)
    f.add(chain([(0, 0.041, 0.537), (0, 0.042, 0.530), (0, 0.039, 0.523)],
                [0.0036, 0.0029, 0.0020]), k=0.002)

    for s in (1, -1):
        socket = (s * lx, 0.0, hip)

        crest = [(s * 0.030, 0.042, 0.585), (s * 0.052, 0.040, 0.600), (s * 0.078, 0.028, 0.607),
                 (s * 0.096, 0.008, 0.603), (s * 0.100, -0.012, 0.592), (s * 0.094, -0.026, 0.574)]
        base = [(s * 0.030, 0.034, 0.560), (s * 0.048, 0.030, 0.545), (s * 0.066, 0.018, 0.530),
                (s * (lx - 0.006), 0.004, hip + 0.015), (s * (lx + 0.000), -0.010, hip + 0.020),
                (s * (lx + 0.004), -0.022, hip + 0.035)]
        shell(f, base, crest, 0.006, s, 0.0026, 0.004)
        f.add(chain(crest, [0.0045, 0.0048, 0.0050, 0.0050, 0.0046, 0.0050]), k=0.004)

        # Крестцово-подвздошный сустав: крыло держится за крестец.
        f.add(Bar((s * 0.012, 0.018, 0.597), (s * 0.030, 0.036, 0.584), 0.0060, 0.0065), k=0.005)
        f.add(Bar((s * 0.016, 0.026, 0.570), (s * 0.031, 0.036, 0.566), 0.0055, 0.0060), k=0.005)

        # Тело подвздошной и край впадины.
        f.add(Egg((s * (lx - 0.008), 0.004, hip + 0.018), (0.012, 0.017, 0.013)), k=0.006)
        f.add(Egg((s * (lx - 0.002), 0.0, hip), (0.0185, 0.0200, 0.0190)), k=0.006)

        # Седалищная кость и бугор, лобковые ветви, симфиз.
        seat = (s * 0.050, 0.016, hip - 0.046)
        f.add(Bar((s * (lx - 0.008), 0.010, hip - 0.010), seat, 0.0065, 0.0075), k=0.005)
        f.add(Egg(seat, (0.0080, 0.0090, 0.0100)), k=0.004)
        # Ветви — дугой, а не рамкой: запирательное отверстие у эталона
        # овальное.
        f.add(chain([(s * (lx - 0.012), -0.014, hip - 0.008), (s * 0.030, -0.030, hip - 0.012),
                     (s * 0.006, -0.035, hip - 0.020)], [0.0058, 0.0054, 0.0056]), k=0.005)
        f.add(chain([(s * 0.006, -0.032, hip - 0.036), (s * 0.026, -0.022, hip - 0.047), seat],
                    [0.0048, 0.0050, 0.0062]), k=0.004)

        # Впадина: чашка по головке бедра, открытая наружу и вниз-вперёд.
        f.cut(Ball(socket, 0.0142), k=0.001)
        f.cut(Ball((s * (lx + 0.013), -0.004, hip - 0.006), 0.0150), k=0.002)

    # Лобковый симфиз — половины сходятся посередине.
    f.add(Egg((0, -0.035, hip - 0.028), (0.0090, 0.0055, 0.0110)), k=0.004)

    # Отверстия крестца — краской, а не вырезом: вырез в три миллиметра
    # после прореживания ложился мятой бумагой.
    holes = []
    for z in (0.590, 0.576, 0.562, 0.549):
        t = (0.600 - z) / 0.062
        y = 0.020 + 0.020 * t - 0.0055
        for s in (1, -1):
            holes.append(Ball((s * (0.0095 - 0.003 * t), y, z), 0.0026))

    part(b, f, 0.0013, "Hips", keep=3400, reach=0.009, dark=holes)


