# Музыка Суда Души — фон зала. Автор, 06.11: «после сборки — займись музыкой для суда».
# 07.11, первая версия (тема Владыки дважды — у виолончелей с ми, у валторны с ми-бемолем):
# «музыка в суде слишком навязчивая, а должна просто добавлять немного атмосферы. Но начало
# мелодии хорошее». Начало — «Своды»: орган держит ре, хор высоко, колокол ре и ля.
#
# Теперь весь круг — эти своды. Мелодии нет: ни темы, ни литавр, ни шагов гармонии под
# мелодией — аккорд меняется раз в несколько тактов, и всё тянется. Слова суда — Смерть
# и судьи — сверху, музыка — воздух зала под ними.
#
# Под голосами: гул Смерти около 42 Гц — её, поэтому ниже 70 Гц ничего (бас и педаль органа —
# с ре малой октавы, 73 Гц). Хор — высоко, над формантами речи; колокол — редко.
# Ударного нет: колокол входа и вердикта бьёт сама игра (SoulCourt.Toll).
#
# Взвешивание — одним намёком: в третьей части хор тихо берёт ми-бемоль над ре
# (нота отказа, та же, что у Магистра) и отпускает его к ре — весы качнулись и замерли.
#
#   1. Своды    (такты 1–8)   — ре: орган, хор ре и ля вверху, колокол ре и ля;
#   2. Тень     (такты 9–14)  — соль-минор: педаль соль, хор си-бемоль и ре;
#   3. Весы     (такты 15–18) — снова ре, хор: ми-бемоль над ре — и назад к ре;
#   4. Ожидание (такты 19–24) — ля: педаль ля, хор до-диез и ми, колокол ля; к кругу — тише.
# 24 такта, темп 54 — 1:47 на круг. Без жребия.
#   python Tools/music/court.py выход.mid [--loop]
import sys
from orchestra import Orchestra, bar, BASS, ORGAN, OOHS, CHOIR, PICC
from score import loop_tempo

BELLS = PICC
s = Orchestra({BELLS: 76, BASS: 84, ORGAN: 60, OOHS: 62, CHOIR: 50}, program={BELLS: 14})


def floor(at, beats, root, vel=60):
    """Педаль органа: корень и октава над ним, бас — тот же корень."""
    s.add(ORGAN, root, at, beats, vel)
    s.add(ORGAN, root + 12, at, beats, vel - 12)
    s.add(BASS, root, at, beats, vel + 6)


def air(at, beats, notes, vel):
    for p in notes:
        s.add(OOHS, p, at, beats, vel)


# 1. Своды — такты 1–8: то самое начало, вдвое дольше
at = bar(1)
floor(at, 32, 38, 62)
air(at, 16, [74], 40)
air(at + 4, 12, [81], 36)
air(at + 16, 16, [74, 81], 36)
s.swell(OOHS, at, bar(5), 50, 100)
s.swell(OOHS, bar(5), bar(9), 100, 80)
s.add(BELLS, 62, at, 8, 74)
s.add(BELLS, 57, at + 8, 8, 70)

# 2. Тень — такты 9–14: соль-минор, ре вверху остаётся (общий звук)
at = bar(9)
floor(at, 24, 43, 58)
air(at, 24, [74], 36)
air(at + 4, 20, [70], 32)
s.swell(OOHS, at, at + 12, 80, 95)
s.swell(OOHS, at + 12, at + 24, 95, 80)
s.add(BELLS, 55, at + 8, 8, 58)

# 3. Весы — такты 15–18: ре; хор берёт ми-бемоль над ре и отпускает к ре
at = bar(15)
floor(at, 16, 38, 60)
air(at, 16, [74], 34)
s.add(OOHS, 75, at + 2, 6, 30)       # нота отказа — тихо, на миг
s.add(OOHS, 74, at + 8, 8, 30)
s.add(CHOIR, 62, at, 16, 30)
s.swell(CHOIR, at, at + 16, 60, 90)

# 4. Ожидание — такты 19–24: ля, без разрешения; к шву — тише, круг начнётся с ре
at = bar(19)
floor(at, 24, 45, 58)
air(at, 16, [73, 76], 32)
air(at + 16, 8, [76], 28)
s.swell(OOHS, at, at + 24, 85, 60)
s.swell(CHOIR, at, at + 8, 90, 0)
s.add(BELLS, 57, at + 4, 8, 60)

length = bar(25)
tempo = 60e6 / 54
if '--loop' in sys.argv:
    s.repeat(length)                         # второй проход вырезается: хвост зала уже в начале
    tempo = loop_tempo(54, length)           # круг кратен блоку синтезатора (43-SOUND, «Шов петли»)
s.save(sys.argv[1], 60e6 / tempo)
print(f'{sys.argv[1]}: нот {s.count()}, конец на {s.end()} долях = {s.end() * tempo / 1e6:.0f} с'
      + (f'; петля — с {length * tempo / 1e6:.6f} по {2 * length * tempo / 1e6:.6f} с' if '--loop' in sys.argv else ''))
