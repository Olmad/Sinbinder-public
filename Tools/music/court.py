# Музыка Суда Души — фон зала. Автор, 06.11: «после сборки — займись музыкой для суда».
#
# Первая версия (06.11) — тема Владыки дважды, у виолончелей и у валторны. Автор, 07.11:
# «слишком навязчивая, а должна просто добавлять немного атмосферы. Но начало хорошее».
# Вторая (07.11) — только начало: орган, хор, колокола. Автор: «по прежнему не очень
# подходит. Должен быть спокойный суд, а мелодия такая, как будто от вердикта зависит судьба
# мира. Нужна более спокойная, судебная и фоновая». Орган, хор и колокол — собор и рок.
#
# Третья — тихое обсуждение: суд взвешивает, а не грозит.
#   * медленные струнные (мягкая подложка) — аккорд раз в два такта; каждые восемь тактов —
#     домой, в ре-минор: ни доминанты, ждущей разрешения, ни нарастания;
#   * маятник — пиццикато качается между двумя нотами раз в две секунды: весы, часы зала;
#   * рояль — одна тихая нота раз в два такта, сверху.
# Ни органа, ни хора, ни колокола, ни литавр. Ниже 70 Гц ничего: гул Смерти — её.
#
# Ре-минор, темп 60, 24 такта — 96 с на круг. Без жребия.
#   python Tools/music/court.py выход.mid [--loop]
import sys
from orchestra import Orchestra, bar, PAD, CELLO, PIANO
from score import loop_tempo

PIZZ = CELLO
s = Orchestra({PAD: 74, PIZZ: 74, PIANO: 58}, program={PIZZ: 45})

# (аккорд струнных, маятник: корень и квинта, нота рояля) — по два такта
CHORDS = {
    'Dm':   ([50, 53, 57, 64], (38, 45), 69),
    'Bb':   ([46, 50, 53, 57], (46, 53), 65),
    'Gm':   ([50, 55, 58, 62], (43, 50), 70),
    'Asus': ([50, 52, 57, 64], (45, 52), 64),
    'F':    ([48, 53, 57, 60], (41, 48), 72),
}
PLAN = ['Dm', 'Bb', 'Gm', 'Dm',
        'Dm', 'Bb', 'F', 'Asus',
        'Dm', 'Gm', 'Bb', 'Dm']

for i, name in enumerate(PLAN):
    at = bar(1 + 2 * i)
    pad, (root, fifth), top = CHORDS[name]
    for p in pad:
        s.add(PAD, p, at, 8, 46)
    # маятник: раз в две доли, корень — квинта — корень — квинта
    for k in range(4):
        s.add(PIZZ, root if k % 2 == 0 else fifth, at + 2 * k, 1.5, 44 if k % 2 == 0 else 38)
    # рояль: одна нота на второй доле, тихо
    s.add(PIANO, top, at + 1, 6, 34)

# дыхание подложки: чуть громче к середине каждой восьмёрки тактов и назад
for half in range(3):
    at = bar(1 + 8 * half)
    s.swell(PAD, at, at + 16, 72, 88)
    s.swell(PAD, at + 16, at + 32, 88, 72)

length = bar(25)
tempo = 60e6 / 60
if '--loop' in sys.argv:
    s.repeat(length)                         # второй проход вырезается: хвост зала уже в начале
    tempo = loop_tempo(60, length)           # круг кратен блоку синтезатора (43-SOUND, «Шов петли»)
s.save(sys.argv[1], 60e6 / tempo)
print(f'{sys.argv[1]}: нот {s.count()}, конец на {s.end()} долях = {s.end() * tempo / 1e6:.0f} с'
      + (f'; петля — с {length * tempo / 1e6:.6f} по {2 * length * tempo / 1e6:.6f} с' if '--loop' in sys.argv else ''))
