# Музыка Суда Души, пятая версия — «заседание». В игре с 07.11 (автор: «ставь»).
#
# Третья (court.py) — тихое обсуждение: автор, 07.11: «Неплохо. Она теперь не такая навязчивая.
# Но попробуй… в стиле „повседневный суд“». Четвёртая (court_daily.py) — шаг баса, клавесин,
# фагот и кларнет в ре-дорийском. Автор: «теперь звучит не как суд, а как прогулка по зелёному
# лугу, нюхая цветочки». Светлый лад, деревянные духовые и шагающий бас — пастораль.
#
# Пятая — третья, которая понравилась (минор, низкие струнные, маятник), и в ней идёт
# заседание: дело за делом, без рока и без луга.
#   * подложка струнных и маятник пиццикато — как в третьей: корень и квинта раз в две доли;
#   * писарь — рояль внизу середины, тихие отрывистые восьмые по звукам аккорда, сверху
#     всё время одно ре: перо скрипит, часы идут, дело не кончается. Входит с пятого такта
#     и молчит в последних двух — круг начинается и кончается тишиной зала;
#   * виолончель зачитывает дело — на одной ноте (ля), как читают протокол, с поворотом
#     в конце фразы: дважды «отложено» (на ля), дважды «решено» (вниз, в ре).
# Ни деревянных духовых, ни клавесина, ни органа, ни хора, ни колокола. Ре-минор, темп 66,
# 24 такта — 87 с на круг. Ниже 70 Гц ничего: гул Смерти — её (самый низ — ре, 73 Гц).
# Без жребия.
#   python Tools/music/court_session.py выход.mid [--loop]
import sys
from orchestra import Orchestra, bar, PAD, CELLO, BASS, PIANO
from score import loop_tempo

PIZZ = BASS
s = Orchestra({PAD: 74, PIZZ: 74, PIANO: 52, CELLO: 70}, program={PIZZ: 45})

# аккорд: подложка, маятник (корень, квинта), ячейка писаря (четыре восьмые, сверху ре)
CHORDS = {
    'Dm':   ([50, 53, 57, 64], (38, 45), [62, 57, 53, 57]),
    'Bb':   ([46, 50, 53, 57], (46, 53), [62, 58, 53, 58]),
    'Gm':   ([50, 55, 58, 62], (43, 50), [62, 58, 55, 58]),
    'Asus': ([50, 52, 57, 64], (45, 52), [62, 57, 52, 57]),
    'A':    ([49, 52, 57, 64], (45, 52), [61, 57, 52, 57]),
}
PLAN = ['Dm', 'Bb', 'Gm', 'Asus',
        'Dm', 'Bb', 'Gm', 'A',
        'Dm', 'Gm', 'Bb', 'Dm']          # по два такта

for i, name in enumerate(PLAN):
    at = bar(1 + 2 * i)
    pad, (root, fifth), cell = CHORDS[name]
    for p in pad:
        s.add(PAD, p, at, 8, 46)
    for k in range(4):
        s.add(PIZZ, root if k % 2 == 0 else fifth, at + 2 * k, 1.5, 44 if k % 2 == 0 else 38)
    # писарь: такты 5–22
    for b in range(2):
        n = 1 + 2 * i + b
        if not 5 <= n <= 22:
            continue
        for e in range(8):
            s.add(PIANO, cell[e % 4], bar(n) + e * 0.5, 0.4, 32 if e % 4 == 0 else 25)

# виолончель зачитывает дело: (такт, доля, нота, длина)
READ = [
    # «…отложено» — на ля
    (7, 1.0, 57, .5), (7, 1.5, 57, .5), (7, 2.0, 57, 1.0), (7, 3.0, 55, .5), (7, 3.5, 57, .5),
    (8, 0.0, 55, 1.0), (8, 1.0, 57, 2.5),
    # «…решено» — вниз, в ре
    (11, 1.0, 57, .5), (11, 1.5, 57, .5), (11, 2.0, 58, .5), (11, 2.5, 57, .5), (11, 3.0, 55, 1.0),
    (12, 0.0, 53, 1.0), (12, 1.0, 52, 1.0), (12, 2.0, 50, 2.0),
    # «…отложено»
    (15, 1.0, 57, .5), (15, 1.5, 57, .5), (15, 2.0, 57, .5), (15, 2.5, 59, .5), (15, 3.0, 57, 1.0),
    (16, 0.0, 55, 1.0), (16, 1.0, 52, 1.0), (16, 2.0, 57, 2.0),
    # «…решено» — последнее слово круга
    (21, 1.0, 57, .5), (21, 1.5, 57, .5), (21, 2.0, 57, 1.0), (21, 3.0, 58, 1.0),
    (22, 0.0, 57, 1.0), (22, 1.0, 55, 1.0), (22, 2.0, 53, 2.0),
    (23, 0.0, 52, 1.0), (23, 1.0, 50, 3.0),
]
for b, beat, p, d in READ:
    s.add(CELLO, p, bar(b) + beat, d, 48)

# дыхание подложки, как в третьей
for half in range(3):
    at = bar(1 + 8 * half)
    s.swell(PAD, at, at + 16, 72, 88)
    s.swell(PAD, at + 16, at + 32, 88, 72)

length = bar(25)
bpm = 66
tempo = 60e6 / bpm
if '--loop' in sys.argv:
    s.repeat(length)                         # второй проход вырезается: хвост зала уже в начале
    tempo = loop_tempo(bpm, length)          # круг кратен блоку синтезатора (43-SOUND, «Шов петли»)
s.save(sys.argv[1], 60e6 / tempo)
print(f'{sys.argv[1]}: нот {s.count()}, конец на {s.end()} долях = {s.end() * tempo / 1e6:.0f} с'
      + (f'; петля — с {length * tempo / 1e6:.6f} по {2 * length * tempo / 1e6:.6f} с' if '--loop' in sys.argv else ''))
