# Тема Безымянного — героя демо. Автор, 9 октября: чувство — «скитание
# в поисках свободы с оттенком надежды». В архиве автора темы нет — она своя.
#
# Мотив — «четыре шага вперёд, один назад»: ре–ми–фа–соль, ля — и шаг назад,
# на соль. Пешка ходит только вперёд; шаг назад может сделать только тот,
# у кого есть своя воля (`44-LORE.md`). Дальше мотив идёт тем же шагом
# по новым местам — дорога без конца.
#
# Скитание — гармония не сидит дома: ре минор, соль МАЖОР, до, фа, си-бемоль,
# ля. Надежда — си-бекар (дорийский ре: соль мажор вместо соль минора)
# и середина в фа мажоре; мрак — си-бемоль: дорога то светлеет, то нет.
# Шаги — пиццикато внизу, четвертями: идёт, а не стоит. Голос — английский
# рожок, один, как путник; в середине его подхватывает валторна.
# Ни литавр, ни хора, ни меди всем: это не бой и не Владыка.
#
#   1. Дорога      (0:00) — одни шаги: пиццикато, тихие струнные;
#   2. Путник      (0:13) — рожок: мотив и шестнадцать тактов пути;
#   3. Надежда     (1:04) — валторна ведёт в фа мажоре, рожок отвечает, арфа;
#   4. Снова путь  (1:55) — рожок, под ним виолончели тянут терции; к ля — и в начало.
# 52 такта, 2:46, петля. Темп 75. Без жребия.
#   python3 Tools/music/nameless_concept.py выход.mid [--loop]
import sys
from score import loop_tempo
from orchestra import (Orchestra, CHORD, bar, HORN, STR, PAD, CELLO, BASS, HARP, CEL, PIANO, OOHS)

EH, PIZZ = CEL, PIANO
s = Orchestra({EH: 112, PIZZ: 127, HORN: 96, STR: 96, PAD: 74, CELLO: 96, BASS: 92, HARP: 84,
               OOHS: 76}, program={EH: 69, PIZZ: 45})

# мелодия пути: (нота, начало, длина) в долях от начала части, 16 тактов
ROAD = [(62, 0, 1), (64, 1, 1), (65, 2, 1), (67, 3, 1),          # ре минор: четыре шага вперёд
        (69, 4, 2), (67, 6, 1), (65, 7, 1),                       # ля — и шаг назад
        (62, 8, 1), (67, 9, 1), (69, 10, 1), (71, 11, 1),         # соль мажор: снова вперёд, си-бекар
        (74, 12, 2), (71, 14, 1), (69, 15, 1),                    # дальше прежнего — и назад
        (69, 16, 1.5), (67, 17.5, 0.5), (65, 18, 1), (64, 19, 1), # ре минор
        (62, 20, 1), (65, 21, 1), (69, 22, 2),
        (67, 24, 1.5), (65, 25.5, 0.5), (64, 26, 1), (62, 27, 1), # до
        (64, 28, 3),
        (65, 32, 1), (67, 33, 1), (69, 34, 1), (72, 35, 1),       # фа: мотив выше
        (77, 36, 2), (76, 38, 1), (72, 39, 1),
        (76, 40, 2), (74, 42, 1), (72, 43, 1),                    # до
        (67, 44, 3),
        (65, 48, 1), (67, 49, 1), (69, 50, 1), (70, 51, 1),       # си-бемоль: дорога темнеет
        (74, 52, 2), (72, 54, 1), (70, 55, 1),
        (69, 56, 1), (67, 57, 1), (65, 58, 1), (64, 59, 1),       # ля
        (64, 60, 2), (61, 62, 1), (64, 63, 1)]
ROAD_CH = ['Dm', 'Dm', 'G', 'G', 'Dm', 'Dm', 'C', 'C', 'F', 'F', 'C', 'C', 'Bb', 'Bb', 'A', 'A']

# надежда: тот же мотив в фа мажоре у валторны
HOPE = [(65, 0, 1), (67, 1, 1), (69, 2, 1), (70, 3, 1),
        (72, 4, 2), (70, 6, 1), (69, 7, 1),
        (67, 8, 1), (69, 9, 1), (71, 10, 1), (72, 11, 1),
        (76, 12, 2), (74, 14, 1), (72, 15, 1),
        (69, 16, 1.5), (67, 17.5, 0.5), (65, 18, 1), (64, 19, 1),
        (62, 20, 1), (65, 21, 1), (70, 22, 2),
        (69, 24, 1.5), (67, 25.5, 0.5), (65, 26, 1), (69, 27, 1),
        (67, 28, 3),
        (67, 32, 1), (71, 33, 1), (74, 34, 2),                    # соль мажор — самое светлое место
        (76, 36, 2), (74, 38, 1), (71, 39, 1),
        (69, 40, 2), (65, 42, 1), (69, 43, 1),
        (67, 44, 2), (64, 46, 2),
        (65, 48, 1), (67, 49, 1), (69, 50, 1), (70, 51, 1),
        (72, 52, 2), (69, 54, 2),
        (70, 56, 1), (69, 57, 1), (67, 58, 1), (65, 59, 1),
        (64, 60, 3)]
HOPE_CH = ['F', 'F', 'C', 'C', 'Dm', 'Bb', 'F', 'C', 'G', 'G', 'Dm', 'C', 'Bb', 'F', 'Gm', 'A']
# ответы рожка в паузах валторны (такты 4, 8, 12, 16 части)
ANSWERS = [(14, [(67, 0, 1), (69, 1, 1)]), (29, [(62, 0, 1), (64, 1, 1), (65, 2, 1)]),
           (46, [(71, 0, 1), (74, 1, 1)]), (61, [(61, 0, 1), (64, 1, 2)])]


def steps(at, chords, vel=74, half=False):
    """Шаги: пиццикато внизу — корень, квинта, корень, квинта; half — шагом
    медленнее (половинными). Каждый восьмой такт — без шагов: путник остановился."""
    for b, name in enumerate(chords):
        if b % 8 == 7: continue
        r = CHORD[name]['cello']
        beats = (0, 2) if half else (0, 1, 2, 3)
        for k, st in enumerate(beats):
            s.add(PIZZ, r if k % 2 == 0 else r + 7, at + b * 4 + st, 0.6, vel + (8 if st == 0 else 0))


def pad(at, chords, vel):
    for b, name in enumerate(chords):
        for p in CHORD[name]['mid']: s.add(PAD, p, at + b * 4, 4, vel)
        s.add(BASS, CHORD[name]['bass'] + 12, at + b * 4, 4, vel - 6)


def harp(at, chords, vel):
    """Арфа вверх по аккорду восьмыми — только на сильную половину такта."""
    for b, name in enumerate(chords):
        c = CHORD[name]
        for k, p in enumerate([c['cello'] + 12, *c['mid']]):
            s.add(HARP, p, at + b * 4 + k * 0.5, 2, vel + (6 if k == 0 else 0))


# 1. Дорога — такты 1–4: одни шаги
steps(bar(1), ['Dm', 'Dm', 'Dm', 'A'], 70)
pad(bar(1), ['Dm', 'Dm', 'Dm', 'A'], 30)

# 2. Путник — такты 5–20
at = bar(5)
s.line(EH, ROAD, at, 92)
steps(at, ROAD_CH, 74)
pad(at, ROAD_CH, 42)

# 3. Надежда — такты 21–36: валторна в фа мажоре, рожок отвечает
at = bar(21)
s.line(HORN, HOPE, at, 90)
for st, notes in ANSWERS: s.line(EH, notes, at + st, 78)
steps(at, HOPE_CH, 72, half=True)
pad(at, HOPE_CH, 46)
harp(at, HOPE_CH, 50)
for p in (57, 62): s.add(OOHS, p, bar(29), 16, 40)                       # тихий хор на соль мажоре
s.swell(OOHS, bar(29), bar(33), 70, 100)

# 4. Снова путь — такты 37–52: рожок, под ним виолончели тянут терции аккордов
at = bar(37)
s.line(EH, ROAD, at, 96)
for b, name in enumerate(ROAD_CH):                                          # виолончели: терция аккорда, по такту
    s.add(CELLO, CHORD[name]['mid'][1] - 12 if CHORD[name]['mid'][1] - 12 >= 45 else CHORD[name]['mid'][1], at + b * 4, 4, 62)
steps(at, ROAD_CH, 76)
pad(at, ROAD_CH, 46)
for p in CHORD['A']['mid']: s.add(STR, p + 12, bar(51), 8, 56)              # ля ждёт ре — и дорога снова
s.swell(STR, bar(51), bar(53), 70, 30)

LENGTH = bar(53)
tempo = loop_tempo(76, LENGTH)
if '--loop' in sys.argv:
    s.repeat(LENGTH)
s.save(sys.argv[1], 60e6 / tempo)
sec = LENGTH * tempo / 1e6
print(f'{sys.argv[1]}: нот {s.count()}, темп {60e6 / tempo:.2f}, круг {sec:.6f} с'
      + (f'; петля — с {sec:.6f} по {2 * sec:.6f} с' if '--loop' in sys.argv else ''))
