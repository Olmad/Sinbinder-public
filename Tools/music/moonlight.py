TEMPO = 56          # четверть: Adagio sostenuto, у «Крыс» — спокойный шаг
BARS = len(TRIPLETS)


def at(b, beat=0.0):
    """Такт b (с единицы), доля в четвертях."""
    return bar(b) + beat


def who(b):
    """Кто ведёт мелодию в такте: (канал, сдвиг, сила). По фразам, не вместе."""
    # Фагот — на высоте оригинала, а не октавой ниже: ниже он ложился в регистр
    # триолей (соль-диез — ми) и тонул в арфе (замер: −38 против −40,5 дБ(A)).
    # Высокий фагот жалобный — как раз голос отряда.
    if b <= 9:  return BSN, 0, 82
    if b <= 14: return CLAR, 0, 74
    if b <= 20: return OBOE, 0, 72
    return BSN, 0, 80


def sonata():
    s = Orchestra({BSN: 108, CLAR: 96, OBOE: 86, PIZZ: 104, PIANO: 120, CELLO: 84, BASS: 86},
                  program={**FOREST, PIANO: 46})                 # арфа — на канале рояля

    for b, row in TRIPLETS.items():
        for i, p in enumerate(row):
            t = at(b, i / 3)
            s.add(PIANO, p, t, 0.62, 66 + (8 if i % 3 == 0 else 0) + (4 if i == 0 else 0))
            if i % 3 == 0:
                s.add(PIZZ, p - 12, t, 0.3, 60)                     # лапки: тихо, первой нотой тройки

    for b, st, d, p in LOWS:
        s.add(CELLO if p >= 40 else BASS, p, at(b, st), d, 60 if p >= 40 else 56)

    for b, st, d, p in MELODY:
        ch, shift, vel = who(b)
        s.add(ch, p + shift, at(b, st), d, vel - (10 if d < 0.5 else 0))

    # Подпись: такт 23 — до-диез минор, арфа тройками, фагот — мотив «Крыс»
    # от до-диез; такт 24 — аккорд держат и гасят.
    end = BARS + 1
    for i in range(12):
        p = (56, 61, 64)[i % 3]
        s.add(PIANO, p, at(end, i / 3), 0.62, 58 + (8 if i % 3 == 0 else 0))
    s.add(CELLO, 49, at(end), 8, 54); s.add(BASS, 37, at(end), 8, 50)
    for p, st, d in MOTIF:
        s.add(BSN, p - 50 + 49, at(end, st * 1.0), d, 80)
    for p in (49, 56, 61, 64):
        s.add(PIANO, p, at(end + 1), 4, 52)
    for ch in (CELLO, BASS, PIANO):
        s.swell(ch, at(end + 1), at(end + 2), 100, 0)
    return s, TEMPO, at(end + 2)


