# Охотники — тема Ордена (черновики, 23 октября).
#
# Автор послушал: «Гимн не похож на гимн, а скорее как тема деревни Охотников,
# или города, или церкви. Но точно не гимн» — теперь «Обитель Ордена» (abode),
# тема места. «Ловчие идут — вообще не о чём» — марш оставлен ради архива.
#
# Автор: «Похоже у всех Греховодов и их отрядов будут свои темы. Подумать бы
# над темой Охотников». Охотники — Орден: живые, «свет» в собственных глазах,
# германские имена, «Молот Ведьм». Их язык — противоположность «Крысам»:
#
#   Крысы                         Охотники
#   деревянные, пиццикато         рога, мужской хор, орган, колокол, барабан
#   бегут по кругу без выхода     идут ровно, не сворачивая
#   уменьшённое трезвучие         дорийский лад, пустые квинты (органум)
#   выжить                        гимн: для них — праведность, для нас — ужас
#
# Мотив — автора: рог ре–ми–фа–соль из «The Hunt Begins» (во второй волне он
# уже звучит в «The Hunted»). Охота поднимается ступенями и не сворачивает —
# крысы бегут по кругу.
#
#   python3 Tools/music/hunters.py <пьеса> выход.mid
#   пьесы: abode march
import sys
from orchestra import (Orchestra, bar, HORN, STR, PAD, CELLO, BASS, BONE, CHOIR,
                       TIMP, ORGAN, CEL, PICC, BD, SD)
from battles import drum

BELL = CEL                                       # колокол — на канале челесты
ORDER = {BELL: 14, CHOIR: 52, ORGAN: 19}         # колокола, хор «а», церковный орган

# Мотив автора: рог ре–ми–фа–соль.
CALL = [(62, 0, 1), (64, 1, 1), (65, 2, 1), (67, 3, 3)]


def organum(s, notes, at, vel, ch=CHOIR, fifth=True):
    """Мелодия и квинта под ней — как пели в храме до гармонии: пусто и строго."""
    for p, st, d in notes:
        s.add(ch, p, at + st, d, vel)
        if fifth: s.add(ch, p - 7, at + st, d, vel - 8)


def call(s, at, vel=88, shift=0, both=True):
    """Рог зовёт: мотив автора; вторая валторна квартой ниже — охота в два рога."""
    for p, st, d in CALL:
        s.add(HORN, p + shift, at + st, d, vel)
        if both: s.add(HORN, p + shift - 5, at + st, d, vel - 10)


def toll(s, at, p=62, vel=84):
    """Колокол — ре, долго. Ниже малой октавы трубчатый колокол гудит
    кашей, поэтому — первая октава."""
    s.add(BELL, p, at, 6, vel)


def abode():
    """«Обитель Ордена» (задумывался гимном). Хор поёт хорал в дорийском ре — мелодия и квинта под
    ней; орган держит ре и ля; рога зовут мотивом автора между строками;
    процессия — большой барабан на раз. В конце — пустая квинта: без терции,
    ни мажор, ни минор — вера без сомнения. 24 такта, около 1:27."""
    s = Orchestra({CHOIR: 104, HORN: 96, ORGAN: 72, BONE: 84, BELL: 116, TIMP: 118, STR: 70,
                   BASS: 84, 9: 116}, program=ORDER)
    P1 = [(62, 0, 2), (64, 2, 2), (65, 4, 2), (67, 6, 2), (69, 8, 4), (67, 12, 2), (65, 14, 2),
          (64, 16, 4), (62, 20, 4)]                                         # ре–ми–фа–соль — ля… ре
    P2 = [(69, 0, 2), (71, 2, 2), (72, 4, 2), (74, 6, 2), (72, 8, 4), (71, 12, 2), (69, 14, 2),
          (67, 16, 4), (69, 20, 4)]                                         # си — дорийский, не минор
    P3 = [(74, 0, 2), (72, 2, 2), (71, 4, 2), (69, 6, 2), (67, 8, 2), (69, 10, 2), (71, 12, 2),
          (67, 14, 2), (69, 16, 8)]
    P4 = [(62, 0, 2), (64, 2, 2), (65, 4, 2), (67, 6, 2), (69, 8, 2), (67, 10, 2), (65, 12, 2),
          (64, 14, 2), (62, 16, 8)]

    def drone(at, bars, vel=56):
        s.add(ORGAN, 38, at, bars * 4, vel); s.add(ORGAN, 45, at, bars * 4, vel - 6)

    def procession(at, bars, vel=84):
        for b in range(bars):
            drum(s, BD, at + b * 4, vel)
            if b % 2: drum(s, SD, at + b * 4 + 3, vel - 22)

    # 1–2: колокол, орган, рог зовёт
    toll(s, bar(1)); drone(bar(1), 24)
    call(s, bar(2), 80, both=False)
    # 3–8: первая строка — хор, процессия
    organum(s, P1, bar(3), 82)
    procession(bar(3), 6, 80)
    # 9–10: рога — в два голоса
    call(s, bar(9), 90); s.add(TIMP, 38, bar(9), 1, 96); s.add(TIMP, 45, bar(10), 1, 90)
    # 11–16: вторая строка — хор и тромбоны; струнные под ними
    organum(s, P2, bar(11), 88)
    for p, st, d in P2: s.add(BONE, p - 24, bar(11) + st, d, 74)
    procession(bar(11), 6, 86)
    for p in (50, 57): s.add(STR, p, bar(11), 24, 46)
    toll(s, bar(13), 69, 76)
    # 17–22: третья и четвёртая — всё вместе, литавры, колокол
    organum(s, P3[:6], bar(17), 92)
    organum(s, P4[4:], bar(19) + 2 - 8, 90)
    for p, st, d in P4[4:]: s.add(BONE, p - 24, bar(19) + st - 6, d, 78)
    procession(bar(17), 6, 90)
    for b in range(17, 23, 2): s.add(TIMP, 38, bar(b), 1, 100)
    call(s, bar(21), 96)
    # 23–24: пустая квинта — ре и ля; колокол трижды
    for p in (50, 57, 62): s.add(CHOIR, p, bar(23), 8, 80)
    s.add(BONE, 38, bar(23), 8, 70); s.add(BONE, 45, bar(23), 8, 66)
    for k in range(3): toll(s, bar(23) + k * 2.5, 62, 88 - k * 8)
    for ch in (CHOIR, BONE, ORGAN, STR):
        s.swell(ch, bar(23) + 4, bar(25) + 2, 100, 0)
    return s, 66, bar(25)


def march():
    """«Ловчие идут». Орден на марше: полевой барабан ровно, рога ведут мотив
    автора и поднимаются до октавы, как в «The Hunt Begins»; тромбоны держат
    шаг внизу; хор вступает коротко — «Аминь» без слов. Не бегут и не
    торопятся: им некуда спешить — это мы бежим. 32 такта, около 1:14."""
    s = Orchestra({HORN: 100, BONE: 90, CHOIR: 92, STR: 78, CELLO: 88, BASS: 92, TIMP: 120,
                   BELL: 112, ORGAN: 60, 9: 124}, program=ORDER)
    RISE = [(62, 0, 1), (64, 1, 1), (65, 2, 1), (67, 3, 1), (69, 4, 1), (71, 5, 1), (72, 6, 1), (74, 7, 1)]

    def field(at, bars, vel=80):
        """Полевой барабан: раз — два-и — три — четыре, ровно, без дроби."""
        for b in range(bars):
            t = at + b * 4
            for st, v in ((0, 10), (1.5, -10), (2, 4), (3, -6)):
                drum(s, SD, t + st, vel + v)
            drum(s, BD, t, vel + 6)

    def tread(at, roots, vel=74):
        """Шаг внизу: виолончели и тромбоны — корень на раз и три."""
        for b, r in enumerate(roots):
            for h in (0, 2):
                s.add(CELLO, r, at + b * 4 + h, 1.6, vel)
                s.add(BONE, r - 12, at + b * 4 + h, 1.6, vel - 10)

    D = [38, 38, 36, 38, 41, 40, 38, 38]          # ре, ре, до, ре, фа, ми, ре — дорийский, без ми-бемоля
    # 1–8: барабан, шаг, рог зовёт
    field(bar(1), 8, 72)
    tread(bar(1), D, 70)
    call(s, bar(3), 86, both=False); call(s, bar(7), 88)
    # 9–16: рога поднимаются до октавы — дважды, второй раз с хором
    field(bar(9), 8, 78)
    tread(bar(9), D, 74)
    s.line(HORN, RISE, bar(9), 92, hold=3); s.line(HORN, RISE, bar(9), 80, shift=-5, hold=3)
    s.line(HORN, RISE, bar(13), 96, hold=3)
    organum(s, [(p, st, d) for p, st, d in RISE], bar(13), 74)
    # 17–24: строже — струнные ровными четвертями на ре и ля, колокол
    field(bar(17), 8, 82)
    for b in range(8):
        for q in range(4):
            s.add(STR, 50 if q % 2 == 0 else 57, bar(17) + b * 4 + q, 0.8, 58 + (8 if q == 0 else 0))
    tread(bar(17), D, 78)
    for b in (17, 21): toll(s, bar(b), 62, 84)
    organum(s, [(69, 0, 4), (67, 4, 4), (65, 8, 4), (64, 12, 4), (62, 16, 8)], bar(19), 82)
    # 25–32: всё вместе — рога, хор «аминь» на ре и ля, к концу — тише: прошли мимо
    field(bar(25), 6, 86)
    tread(bar(25), D[:6], 80)
    call(s, bar(25), 96); call(s, bar(27), 96, shift=7)
    organum(s, [(62, 0, 4), (69, 4, 8)], bar(29), 86)              # «А-минь» — без слов
    s.add(TIMP, 38, bar(31), 1, 98); s.add(TIMP, 45, bar(31) + 2, 1, 90)
    toll(s, bar(31), 62, 80)
    for ch in (HORN, CHOIR, BONE, CELLO):
        s.swell(ch, bar(31), bar(33), 100, 0)
    return s, 104, bar(33)


PIECES = {'abode': abode, 'march': march}

if __name__ == '__main__':
    name, out = sys.argv[1], sys.argv[2]
    s, bpm, length = PIECES[name]()
    s.save(out, bpm)
    print(f'{out}: {name}, нот {s.count()}, темп {bpm}, конец на {s.end() * 60 / bpm:.1f} с')
