# Короткие сигналы из архива автора — по задумке, под события игры.
#   python3 Tools/music/stingers.py spark|fallen выход.mid
#
# «Spark of Eternity» — у автора «Новая душа (8 сек)»: челеста ре–фа–ми–ре,
#   темп 80. В игре — воин встаёт в мастерской склепа (душа получила тело).
#   Своё: вспышка арфы перед мотивом — искра; под мотивом ре минор, ля
#   и в конце ре МАЖОР — искра загорелась. Челеста здесь — автора, и это
#   ровно то место, где автор её слышит: тихо, одна, в склепе.
#
# «Whisper of the Fallen» — у автора «Смерть союзника (12 сек)»: ре и си-
#   бемоль внизу, хор шёпотом, темп 60. В игре — Карган пал, прикрывая отход:
#   легенда, которая осталась сама. Своё: виолончель одна поёт тему Владыки
#   вниз — ре–ля–соль–фа–ми–ре, как плач; под ми — си-бемоль (то же ми над
#   си-бемолем, что в «A Lord Returns»), и развязки нет: последнее ре — над
#   си-бемолем. Темп 72 — чтобы уложиться в задуманные двенадцать секунд.
# Без жребия.
import sys
from orchestra import Orchestra, PAD, CELLO, BASS, HARP, OOHS, CEL

kind, out = sys.argv[1], sys.argv[2]

if kind == 'spark':
    s = Orchestra({PAD: 70, HARP: 90, OOHS: 80, CEL: 127})
    for k, p in enumerate([50, 53, 57, 62, 65, 69, 74]):              # вспышка: ре минор вверх
        s.add(HARP, p, k * 0.25, 2, 58 + k * 4)
    s.line(CEL, [(74, 0, 2), (77, 2, 2), (76, 4, 2), (74, 6, 3)], 1, 92)  # автора: ре–фа–ми–ре
    for p in (50, 53, 57): s.add(PAD, p, 1, 4, 52)                     # ре минор
    for p in (49, 52, 57): s.add(PAD, p, 5, 2, 54)                     # ля
    for p in (50, 54, 57, 62): s.add(PAD, p, 7, 4, 58)                 # ре мажор — загорелась
    s.expression(PAD, 0, 40); s.swell(PAD, 1, 7, 40, 95)
    for p in (62, 66, 69): s.add(OOHS, p, 7, 4, 50)
    s.add(HARP, 86, 7, 3, 70); s.add(HARP, 74, 7, 3, 64)
    s.save(out, 80)
elif kind == 'fallen':
    s = Orchestra({PAD: 60, CELLO: 110, BASS: 90, OOHS: 110})
    s.line(CELLO, [(50, 0, 2), (45, 2, 2), (43, 4, 2), (41, 6, 2), (40, 8, 2), (38, 10, 4)], 0, 72)
    s.add(BASS, 26, 0, 8, 50); s.add(BASS, 34, 8, 6, 54)               # автора: ре, потом си-бемоль
    for p in (50, 53, 57): s.add(PAD, p, 0, 8, 44)
    for p in (50, 53, 58): s.add(PAD, p, 8, 6, 46)
    s.swell(PAD, 10, 14, 100, 0)
    s.add(OOHS, 50, 4, 4, 56); s.add(OOHS, 50, 10, 4, 52)              # автора: шёпот на ре
    s.save(out, 72)
else:
    sys.exit('spark или fallen')
print(f'{out}: нот {s.count()}, конец на {s.end()} долях')
