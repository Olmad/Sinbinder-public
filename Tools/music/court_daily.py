# Музыка Суда Души, четвёртая версия — «повседневный суд».
#
# Третья (court.py) — тихое обсуждение: струнные, маятник, редкий рояль. Четвёртая (эта) автор
# не принял: «как прогулка по зелёному лугу, нюхая цветочки» — дальше court_session.py.
# Автор, 07.11: «Неплохо. Она теперь не такая навязчивая. Но попробуй сделать ещё 1 версию —
# в стиле „повседневный суд“».
#
# Повседневный — значит обычный день зала: дело за делом, без рока и без угрозы. Суд Души
# идёт после каждого отказа — для Смерти это будни. Отсюда:
#   * бас шагает — пиццикато четвертями, по звукам аккорда и шагом к следующему: дело идёт;
#   * клавесин — тихий аккорд на второй и четвёртой доле: часы зала, перо писаря;
#   * фагот — короткие фразы с паузами, как зачитывают дело; во второй половине круга
#     отвечает кларнет — повыше и полегче, будто писарь переспрашивает;
#   * подложка струнных — еле слышно, чтобы склеить;
#   * печать — один мягкий стук деревяшки в конце каждых шестнадцати тактов.
# Ре-дорийский (си-бекар): светлее ре-минора третьей, но не мажорная бодрость. Темп 88,
# 32 такта — около 87 с на круг. Ниже 70 Гц ничего: гул Смерти — её (самый низ — ре, 73 Гц).
# Без жребия.
#   python Tools/music/court_daily.py выход.mid [--loop]
import sys
from orchestra import Orchestra, bar, PAD, CELLO, HARPSI, HORN, PICC, DRUMS, WOOD_LO
from score import loop_tempo

PIZZ, BSN, CLAR = CELLO, HORN, PICC
s = Orchestra({PAD: 52, PIZZ: 80, HARPSI: 50, BSN: 78, CLAR: 70, DRUMS: 60},
              program={PIZZ: 45, BSN: 70, CLAR: 71})

D2, E2, F2, G2, A2, B2, C3, D3 = 38, 40, 41, 43, 45, 47, 48, 50
# аккорд: корень баса, звуки для шага (терция, квинта), аккорд клавесина, подложка
CH = {
    'Dm': (D2, (41, 45), [57, 62, 65], [50, 53, 57]),
    'G':  (G2, (47, 50), [55, 59, 62], [50, 55, 59]),
    'F':  (F2, (45, 48), [57, 60, 65], [48, 53, 57]),
    'C':  (C3, (52, 55), [55, 60, 64], [48, 52, 55]),
    'Gm': (G2, (46, 50), [55, 58, 62], [50, 55, 58]),
    'Am': (A2, (48, 52), [57, 60, 64], [48, 52, 57]),
    'Bb': (46, (50, 53), [58, 62, 65], [50, 53, 58]),
    'A7': (A2, (49, 52), [55, 61, 64], [49, 52, 55]),
}
PLAN = ['Dm', 'G', 'Dm', 'G', 'F', 'C', 'Gm', 'A7',
        'Bb', 'F', 'Gm', 'Dm', 'Bb', 'C', 'Dm', 'Dm',
        'Dm', 'G', 'Dm', 'G', 'F', 'C', 'Gm', 'A7',
        'Bb', 'F', 'Gm', 'Am', 'Bb', 'C', 'Dm', 'Dm']
SCALE = [38, 40, 41, 43, 45, 47, 48, 50, 52, 53, 55, 57]   # ре-дорийский, D2..A3


def approach(nxt):
    """Шаг к следующему корню — соседняя ступень лада снизу (у ре — сверху)."""
    below = [p for p in SCALE if p < nxt]
    return below[-1] if below and below[-1] >= D2 else min(p for p in SCALE if p > nxt)


# ── бас и клавесин, подложка ──
for i, name in enumerate(PLAN):
    at = bar(1 + i)
    root, (third, fifth), harp, pad = CH[name]
    nxt = CH[PLAN[(i + 1) % len(PLAN)]][0]
    cadence = i % 16 in (14, 15)
    walk = [root, third, fifth, approach(nxt)] if not cadence else [root, fifth, root, fifth]
    for k, p in enumerate(walk):
        s.add(PIZZ, p, at + k, 0.9, 50 if k == 0 else 41)
    if not cadence:
        for k in (1, 3):
            for p in harp:
                s.add(HARPSI, p, at + k, 0.3, 30 if k == 1 else 26)
    for p in pad:
        s.add(PAD, p, at, 4, 34)

# ── фагот: зачитывает дело (такты 1–8 и 17–24) ──
# (такт, доля от начала такта, нота, длина)
READ = [
    (1, 1.0, 57, 0.5), (1, 1.5, 59, 0.5), (1, 2.0, 60, 0.5), (1, 2.5, 62, 1.5),
    (2, 1.0, 59, 0.5), (2, 1.5, 55, 1.5),
    (3, 0.0, 53, 0.5), (3, 0.5, 57, 0.5), (3, 1.0, 62, 1.0), (3, 2.0, 60, 0.5), (3, 2.5, 57, 1.0),
    (4, 1.0, 59, 0.5), (4, 1.5, 55, 0.5), (4, 2.0, 57, 1.5),
    (5, 0.5, 60, 0.5), (5, 1.0, 62, 0.5), (5, 1.5, 64, 0.5), (5, 2.0, 65, 2.0),
    (6, 1.0, 64, 0.5), (6, 1.5, 60, 0.5), (6, 2.0, 55, 1.5),
    (7, 0.0, 58, 0.5), (7, 0.5, 57, 0.5), (7, 1.0, 55, 0.5), (7, 1.5, 53, 1.0),
    (8, 0.0, 52, 1.5), (8, 2.0, 57, 1.0),
]
# второй раз — те же слова, конец другой: дело закрыто, а не отложено
READ2 = READ[:-2] + [(8, 0.0, 52, 1.0), (8, 1.0, 49, 0.5), (8, 1.5, 52, 0.5), (8, 2.0, 55, 1.5),
                     (9, 0.0, 53, 1.5)]       # септима ля-доминанты вниз — в терцию си-бемоля
for base, phrase in ((0, READ), (16, READ2)):
    for b, beat, p, d in phrase:
        s.add(BSN, p, bar(base + b) + beat, d, 52)

# ── кларнет: переспрашивает (такты 9–16 и 25–32), фагот отвечает внизу ──
ASK = [
    (9, 1.0, 74, 0.5), (9, 1.5, 72, 0.5), (9, 2.0, 70, 0.5), (9, 2.5, 69, 1.5),
    (10, 1.0, 72, 1.0), (10, 2.0, 69, 0.5), (10, 2.5, 65, 1.0),
    (11, 1.0, 70, 0.5), (11, 1.5, 69, 0.5), (11, 2.0, 67, 0.5), (11, 2.5, 65, 0.5),
    (12, 0.0, 69, 1.5), (12, 2.0, 62, 1.5),
    (13, 0.5, 65, 0.5), (13, 1.0, 67, 0.5), (13, 1.5, 69, 0.5), (13, 2.0, 70, 2.0),
    (14, 1.0, 72, 1.0), (14, 2.0, 67, 0.5), (14, 2.5, 64, 1.0),
    (15, 0.0, 65, 0.5), (15, 0.5, 64, 0.5), (15, 1.0, 62, 2.0),
]
ANSWER = [(12, 2.5, 57, 1.0), (14, 3.0, 55, 0.5), (14, 3.5, 57, 0.5), (16, 0.0, 50, 2.0)]
for base in (0, 16):
    for b, beat, p, d in ASK:
        s.add(CLAR, p, bar(base + b) + beat, d, 46)
    for b, beat, p, d in ANSWER:
        s.add(BSN, p, bar(base + b) + beat, d, 44)

# ── печать: мягкий стук в конце шестнадцати тактов ──
for b in (16, 32):
    s.add(DRUMS, WOOD_LO, bar(b) + 3, 0.5, 40)

# подложка дышит: чуть слышнее к середине каждой восьмёрки и назад
for half in range(4):
    at = bar(1 + 8 * half)
    s.swell(PAD, at, at + 16, 70, 84)
    s.swell(PAD, at + 16, at + 32, 84, 70)

length = bar(33)
bpm = 88
tempo = 60e6 / bpm
if '--loop' in sys.argv:
    s.repeat(length)                         # второй проход вырезается: хвост зала уже в начале
    tempo = loop_tempo(bpm, length)          # круг кратен блоку синтезатора (43-SOUND, «Шов петли»)
s.save(sys.argv[1], 60e6 / tempo)
print(f'{sys.argv[1]}: нот {s.count()}, конец на {s.end()} долях = {s.end() * tempo / 1e6:.0f} с'
      + (f'; петля — с {length * tempo / 1e6:.6f} по {2 * length * tempo / 1e6:.6f} с' if '--loop' in sys.argv else ''))
