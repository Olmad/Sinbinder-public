# Музыка сна-обучения — «Дорога сна».
#
# Автор, 07.11: «нужно придумать музыку для обучения. Вполне может подойти суд 4. Поставь 4 суд,
# но напиши новую для обучения». Четвёртый суд (court_daily.py) автор назвал «прогулкой по
# зелёному лугу» — для суда мимо, для дороги в самый раз: от него взят шаг. Остальное — сон:
#   * бас шагает пиццикато четвертями — идущий по дороге; через разрушенный форт (вторая
#     половина, такты 17–24) шаг вдвое реже: двор, чучело, камень с банками;
#   * арфа — тихие ломаные аккорды четвертями, во дворе — восьмыми;
#   * челеста — короткий мотив «урока» (ре — ля — соль — фа) в начале круга, как звон
#     над табличкой: вопрос, а не ответ;
#   * флейта — долгие ноты, фразы с паузами; во дворе мелодию берёт кларнет, ниже и теплее;
#     в последней восьмёрке кларнет спускается под флейтой — дорога ведёт вниз, к склепу;
#   * подложка струнных — те же три ноты (фа, ля, ре) над ре, до и си-бемолем: сон стоит,
#     а под ним меняется земля.
# Ре-минор (си-бемоль), во дворе один раз ре-мажор — свет впереди. Темп 76, 32 такта —
# около 101 с на круг. Ниже 70 Гц ничего: гул Смерти — её (самый низ — ре, 73 Гц).
# Громкость за круг ровная: в первой восьмёрке нет мелодии — её держат арфа и челеста;
# во дворе бас реже — арфа гуще. Без жребия.
#   python Tools/music/dream_road.py выход.mid [--loop]
import sys
from orchestra import Orchestra, bar, PAD, CELLO, HARP, CEL, HORN, PICC

PIZZ, CLAR, FLUTE = CELLO, HORN, PICC
s = Orchestra({PAD: 50, PIZZ: 78, HARP: 60, CEL: 60, FLUTE: 74, CLAR: 66},
              program={PIZZ: 45, CLAR: 71, FLUTE: 73})

# аккорд: корень баса, подложка (три голоса)
CH = {
    'Dm':    (50, [53, 57, 62]),
    'Dm/C':  (48, [53, 57, 62]),
    'Bbmaj7': (46, [53, 57, 62]),
    'Gm7':   (43, [53, 58, 62]),
    'Asus':  (45, [52, 57, 62]),
    'A':     (45, [52, 57, 61]),
    'F/A':   (45, [53, 57, 60]),
    'C':     (48, [52, 55, 60]),
    'F':     (41, [53, 57, 60]),
    'A7':    (45, [52, 55, 61]),
    'Bb':    (46, [53, 58, 62]),
    'Am':    (45, [52, 57, 60]),
    'Dsus':  (38, [55, 57, 62]),
    'D':     (38, [54, 57, 62]),
}
PLAN = ['Dm', 'Dm/C', 'Bbmaj7', 'Bbmaj7', 'Gm7', 'Gm7', 'Asus', 'A',        # дорога: только шаг
        'Dm', 'Dm/C', 'Bbmaj7', 'F/A', 'Gm7', 'C', 'F', 'A7',               # флейта
        'Bb', 'C', 'Am', 'Dm', 'Bb', 'C', 'Dsus', 'D',                      # форт: кларнет
        'Dm', 'Dm/C', 'Bbmaj7', 'F/A', 'Gm7', 'Asus', 'A', 'Dm']            # к склепу
SCALE = [38, 40, 41, 43, 45, 46, 48, 50, 52, 53, 55, 57]   # ре-минор, D2..A3
COURTYARD = range(16, 24)


def toward(cur, nxt):
    """Шаг к следующему корню — соседняя ступень лада с той стороны, откуда идём."""
    if nxt > cur:
        below = [p for p in SCALE if p < nxt]
        return below[-1]
    above = [p for p in SCALE if p > nxt]
    return above[0] if nxt != cur else min(57, nxt + 7)


# ── бас, арфа, подложка ──
for i, name in enumerate(PLAN):
    at = bar(1 + i)
    root, pad = CH[name]
    nxt = CH[PLAN[(i + 1) % len(PLAN)]][0]
    fifth = root + 7 if root + 7 <= 57 else root - 5
    third = pad[0] if pad[0] - root <= 12 else pad[0] - 12
    if i in COURTYARD:
        s.add(PIZZ, root, at, 1.8, 46)
        s.add(PIZZ, fifth, at + 2, 1.8, 38)
    else:
        for k, p in enumerate([root, fifth, third, toward(root, nxt)]):
            s.add(PIZZ, p, at + k, 0.9, 46 if k == 0 else 37 if k == 2 else 39)
    up = [p + 12 for p in pad]
    if i in COURTYARD:
        for k, p in enumerate([up[0], up[1], up[2], up[0] + 12, up[2], up[1], up[0], up[1]]):
            s.add(HARP, p, at + k * 0.5, 1.4, 31 if k else 35)
    else:
        for k, p in enumerate([up[0], up[1], up[2], up[1]]):
            s.add(HARP, p, at + k, 1.6, (36 if k == 0 else 30) + (3 if i < 8 else 0))
    for p in pad:
        s.add(PAD, p, at, 4, 34)

# ── челеста: мотив урока (такты 1, 3, 5, 7), в восьмом — вопрос ──
# (такт, доля от начала такта, нота, длина)
LESSON = [
    (1, 1.0, 74, 0.5), (1, 1.5, 81, 0.5), (1, 2.0, 79, 0.5), (1, 2.5, 77, 1.5),
    (3, 1.0, 74, 0.5), (3, 1.5, 81, 0.5), (3, 2.0, 79, 0.5), (3, 2.5, 77, 1.5),
    (5, 1.0, 74, 0.5), (5, 1.5, 82, 0.5), (5, 2.0, 81, 0.5), (5, 2.5, 79, 1.5),
    (7, 1.0, 76, 0.5), (7, 1.5, 81, 0.5), (7, 2.0, 79, 0.5), (7, 2.5, 76, 1.5),
    (8, 1.0, 85, 2.0),
    (12, 2.0, 77, 0.5), (12, 2.5, 81, 0.5), (12, 3.0, 84, 1.0),          # эхо под долгой нотой флейты
]
for b, beat, p, d in LESSON:
    s.add(CEL, p, bar(b) + beat, d, 44 if b <= 8 else 36)

# ── флейта: такты 9–16 и 25–32 ──
FLUTE_A = [
    (9, 0.0, 69, 2.0), (9, 2.0, 74, 1.0), (9, 3.0, 76, 1.0),
    (10, 0.0, 77, 3.0), (10, 3.0, 76, 1.0),
    (11, 0.0, 74, 2.0), (11, 2.0, 69, 2.0),
    (12, 0.0, 72, 4.0),
    (13, 0.0, 70, 1.5), (13, 1.5, 69, 0.5), (13, 2.0, 67, 2.0),
    (14, 0.0, 76, 3.0), (14, 3.0, 74, 1.0),
    (15, 0.0, 72, 2.0), (15, 2.0, 69, 2.0),
    (16, 0.0, 73, 2.0), (16, 2.0, 76, 1.0), (16, 3.0, 67, 1.0),
]
FLUTE_B = [
    (25, 0.0, 69, 2.0), (25, 2.0, 74, 1.0), (25, 3.0, 76, 1.0),
    (26, 0.0, 77, 2.0), (26, 2.0, 79, 1.0), (26, 3.0, 77, 1.0),
    (27, 0.0, 74, 2.0), (27, 2.0, 69, 2.0),
    (28, 0.0, 72, 3.0), (28, 3.0, 69, 1.0),
    (29, 0.0, 70, 2.0), (29, 2.0, 74, 1.0), (29, 3.0, 77, 1.0),
    (30, 0.0, 76, 2.0), (30, 2.0, 74, 2.0),
    (31, 0.0, 73, 2.0), (31, 2.0, 76, 1.0), (31, 3.0, 73, 1.0),
    (32, 0.0, 74, 4.0),
]
for b, beat, p, d in FLUTE_A + FLUTE_B:
    s.add(FLUTE, p, bar(b) + beat, d, 50)

# ── кларнет: двор форта (17–24) — мелодия; к склепу (25–32) — спуск под флейтой ──
YARD = [
    (17, 0.0, 65, 1.0), (17, 1.0, 70, 1.0), (17, 2.0, 74, 2.0),
    (18, 0.0, 72, 1.5), (18, 1.5, 67, 0.5), (18, 2.0, 64, 2.0),
    (19, 0.0, 69, 2.0), (19, 2.0, 72, 1.0), (19, 3.0, 71, 1.0),
    (20, 0.0, 69, 3.0),
    (21, 0.0, 74, 1.0), (21, 1.0, 77, 1.0), (21, 2.0, 74, 2.0),
    (22, 0.0, 76, 1.0), (22, 1.0, 72, 1.0), (22, 2.0, 67, 2.0),
    (23, 0.0, 67, 2.0), (23, 2.0, 69, 2.0),
    (24, 0.0, 66, 4.0),                       # фа-диез — ре-мажор, свет впереди
]
DOWN = [(25, 65), (26, 64), (27, 62), (28, 60), (29, 62), (30, 64), (31, 61), (32, 62)]
for b, beat, p, d in YARD:
    s.add(CLAR, p, bar(b) + beat, d, 52)
for b, p in DOWN:
    s.add(CLAR, p, bar(b), 4, 36)

# подложка дышит: чуть слышнее к середине каждой восьмёрки и назад
for part in range(4):
    at = bar(1 + 8 * part)
    s.swell(PAD, at, at + 16, 70, 84)
    s.swell(PAD, at + 16, at + 32, 84, 70)

length = bar(33)
bpm = 76
tempo = 60e6 / bpm
if '--loop' in sys.argv:
    from score import loop_tempo
    s.repeat(length)                         # второй проход вырезается: хвост зала уже в начале
    tempo = loop_tempo(bpm, length)          # круг кратен блоку синтезатора (43-SOUND, «Шов петли»)
s.save(sys.argv[1], 60e6 / tempo)
print(f'{sys.argv[1]}: нот {s.count()}, конец на {s.end()} долях = {s.end() * tempo / 1e6:.0f} с'
      + (f'; петля — с {length * tempo / 1e6:.6f} по {2 * length * tempo / 1e6:.6f} с' if '--loop' in sys.argv else ''))
