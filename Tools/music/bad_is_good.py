# «Bad is good, but Evil is better» — партитура страницы автора нота в ноту,
# но инструментами, а не волнами: челеста, виолончель (и контрабас октавой
# ниже — страница подкладывала пол-частоты), хор «а», литавры, орган.
# Темп 40: четверть — полторы секунды.
#   python3 Tools/music/bad_is_good.py выход.mid [--octave]
# Паузы закрыты (автор, 2 октября: «КОНЕЧНО»): страница подписывала части
# длиннее, чем писала ноты, — последний долгий звук части теперь держится
# до начала следующей. Новых нот нет, только длины; прежние — в комментариях.
# Сведение — по замеру голосов (levels.py): челеста громче всех, виолончель
# ниже её, хор — шёпотом, как на странице (там он вчетверо тише прочих).
# --octave — вторая версия: где мелодия челесты лежит низко (от «Восхищения»
# до коды, первая октава), она удвоена октавой выше, чуть тише основной.
# Удваивается фраза целиком, а не отдельные ноты. Ноты страницы не тронуты.
import sys
from score import Score

CELESTA, CELLO, BASS, CHOIR, TIMP, ORGAN, HIGH = 0, 1, 2, 3, 4, 5, 6
PROGRAM = {CELESTA: 8, CELLO: 42, BASS: 43, CHOIR: 52, TIMP: 47, ORGAN: 19, HIGH: 8}
VOLUME = {CELESTA: 127, CELLO: 58, BASS: 62, CHOIR: 52, TIMP: 96, ORGAN: 55, HIGH: 120}
PAN = {CELESTA: 72, CELLO: 44, BASS: 54, CHOIR: 82, TIMP: 64, ORGAN: 58, HIGH: 56}
REVERB = {CELESTA: 75, CELLO: 70, BASS: 60, CHOIR: 90, TIMP: 60, ORGAN: 85, HIGH: 85}

octave = '--octave' in sys.argv
s = Score()


def celesta(lst, at, low=False):
    for p, st, d, v in lst:
        s.add(CELESTA, p, at + st, d, 40 + v * 120)
        if octave and low:
            s.add(HIGH, p + 12, at + st, d, 40 + v * 120)


def cello(lst, at):
    for p, st, d, v in lst:
        s.add(CELLO, p, at + st, d, 45 + v * 110)
        s.add(BASS, p - 12, at + st, d, 22 + v * 70)


def choir(lst, at):
    for p, st, d, v in lst:
        s.add(CHOIR, p, at + st, d, 45 + v * 160)


def timpani(lst, at):
    for p, st, d, v in lst:
        s.add(TIMP, p, at + st, min(d, 4), 55 + v * 75)


def organ(lst, at):
    for p, st, d, v in lst:
        s.add(ORGAN, p, at + st, d, 30 + v * 120)


# Вступление — только челеста, тема «Evil in mind»
celesta([[81, 2, 2, .4], [79, 3, 1, .4], [86, 4, 2, .45], [89, 5, 2, .45], [88, 6, 4, .45]], 0)

# Ночная тема — челеста, виолончель, шёпот хора
t1 = 8
celesta([[81, 0, 2, .35], [79, 1, 1, .35], [86, 2, 2, .4], [89, 3, 2, .4], [88, 4, 4, .4],
         [81, 6, 2, .3], [79, 7, 4, .3]], t1)
cello([[38, .5, 8, .35], [41, 2.5, 8, .35], [38, 4.5, 12, .4]], t1)
choir([[50, 1, 1, .08], [50, 3, 1, .08], [62, 5, 2, .1]], t1)

# Восхищение — арпеджио челесты, тёплая виолончель, хор
t2 = 24
celesta([[62, 0, 1, .5], [66, .5, 1, .5], [69, 1, 1, .5], [74, 1.5, 6, .5],
         [62, 2, 1, .4], [66, 2.5, 1, .4], [69, 3, 1, .4], [74, 3.5, 4, .4]], t2, low=True)
cello([[50, .5, 11.5, .4]], t2)   # было 8: держится до «Разочарования»
choir([[74, 1.5, 6, .2]], t2)

# Разочарование — диссонанс виолончели (ре и ми-бемоль разом), хор стонет
t3 = 36
cello([[38, 0, 4, .45], [39, 0, 4, .45], [38, 2, 4, .4], [39, 2, 4, .4]], t3)
choir([[50, 0, 12, .2]], t3)   # было 8: стон держится до «Собирания сил»

# Собирание сил — тема «A Lord Returns» на челесте, шаги виолончели, литавры
t4 = 48
celesta([[62, 0, 1, .45], [57, .5, 1, .45], [55, 1, 1, .45], [53, 1.5, 2, .45], [62, 2, 4, .5]], t4, low=True)
cello([[38, 0, 1, .45], [33, 1, 1, .45], [38, 2, 1, .45], [38, 3, 13, .5]], t4)   # было 4: ре до «Шага»
timpani([[38, 0, 1, .5], [38, 1.5, 1, .55], [38, 2.5, 1, .6], [38, 3.5, 2, .65]], t4)

# Шаг вперёд — все вместе, орган, кульминация
t5 = 64
celesta([[62, 0, 2, .55], [69, .5, 2, .55], [67, 1, 2, .55], [65, 1.5, 2, .55], [64, 2, 4, .6]], t5, low=True)
cello([[50, 0, 2, .5], [57, .5, 2, .5], [55, 1, 2, .5], [53, 1.5, 2, .5], [52, 2, 4, .55]], t5)
choir([[50, 0, 1, .3], [50, 1, 1, .3], [50, 2, 2, .35]], t5)
timpani([[38, 0, 1, .6], [38, 1, 1, .6], [38, 2, 1, .6], [38, 3, 1, .6]], t5)
organ([[38, 0, 2, .4], [45, 0, 2, .4], [50, 0, 2, .4], [38, 3, 13, .45], [66, 3, 13, .45], [69, 3, 13, .45]], t5)   # было 4: аккорд до коды

# Кода — затихание, последние аккорды органа
t6 = 80
celesta([[62, 0, 1, .4], [69, .5, 1, .4], [67, 1, 1, .4], [65, 1.5, 2, .4], [62, 2.5, 4, .35]], t6, low=True)
organ([[50, 0, 4, .3], [45, 0, 4, .3], [38, 0, 4, .3], [50, 4, 6, .25], [45, 4, 6, .25], [38, 4, 6, .25]], t6)
timpani([[38, 4, 4, .5]], t6)

s.write(sys.argv[1], 40, PROGRAM, VOLUME, PAN, REVERB)
print(f'{sys.argv[1]}: нот {s.count()}, конец на {s.end()} долях = {s.end() * 1.5:.1f} с'
      + (', мелодия удвоена октавой выше' if octave else ''))
